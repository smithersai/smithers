#!/usr/bin/env python3
"""Writes reading-data.mjs: the slash and colon code points and the HTML5 named-entity table that the repository
scrub (reading.mjs) folds. Run it with the Python whose Unicode data you want, then commit the output:

    python3 ops/issues/reading-data.py > ops/issues/reading-data.mjs
"""
import html.entities
import json
import sys
import unicodedata

# Look-alikes whose names do not say SOLIDUS or SLASH.
SLASH_LIKE = {"SET MINUS", "BOX DRAWINGS LIGHT DIAGONAL UPPER RIGHT TO LOWER LEFT", "BOX DRAWINGS LIGHT DIAGONAL UPPER LEFT TO LOWER RIGHT",
              "MATHEMATICAL RISING DIAGONAL", "MATHEMATICAL FALLING DIAGONAL", "VERTICAL KANA REPEAT MARK UPPER HALF"}
COLON_LIKE = {"RATIO"}
NOT_COLON = ("SEMICOLON", "COLON SIGN", "COLON EQUALS", "EQUALS COLON", "COLON EQUAL")

slashes, colons = [], []
for cp in range(0x110000):
    c = chr(cp)
    name = unicodedata.name(c, "")
    folded = unicodedata.normalize("NFKC", c)
    if "SOLIDUS" in name or "SLASH" in name or name in SLASH_LIKE or "/" in folded or "\\" in folded:
        slashes.append(cp)
    elif (("COLON" in name and not any(word in name for word in NOT_COLON)) or name in COLON_LIKE or ":" in folded) and ";" not in folded:
        colons.append(cp)

def literal(cps):
    return json.dumps("".join(chr(cp) for cp in cps), ensure_ascii=True)

entities = {name: value for name, value in html.entities.html5.items()}
out = sys.stdout
out.write(f"// Generated by reading-data.py from Python {sys.version.split()[0]}'s Unicode {unicodedata.unidata_version} data and HTML5 entity table. Do not edit.\n")
out.write("/** Every code point named SOLIDUS or SLASH, the look-alikes, and every one NFKC folds to a slash. */\n")
out.write(f"export const SLASH_CHARS = {literal(slashes)}\n")
out.write("/** Every code point named COLON (less semicolons and colon signs), RATIO, and every one NFKC folds to a colon. */\n")
out.write(f"export const COLON_CHARS = {literal(colons)}\n")
out.write("/** HTML5 named character references: `name;` and the legacy names a browser also reads without the semicolon. */\n")
out.write(f"export const ENTITIES = {json.dumps(entities, ensure_ascii=True, separators=(',', ':'), sort_keys=True)}\n")

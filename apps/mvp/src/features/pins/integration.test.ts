const opened: Array<{ dispose: () => Promise<void> }> = []
afterEach(async () => { for (const r of opened.reverse().splice(0)) await r.dispose() })
const until = (check: () => void | Promise<void>) => vi.waitFor(check, { timeout: 25_000, interval: 20 })
const open = async (api: TestChatApi["Service"], device: NodeDevice) => {
  const runtime = openTab(api, { host: device, retry: SyncPolicy.backoff({ initial: "20 millis", max: "50 millis" }) })
  opened.push(runtime)
  const chat = await runtime.runPromise(Effect.service(Chat))
  const store = await runtime.runPromise(Effect.service(ChatStore))
  for (const q of [store.shown, store.pinned, store.pinState.collapseState]) q.tanstack.startSyncImmediate()
  return { runtime, ...chat, store, pin: () => chat.queries.pinned.toArray.map(r => r.text) }
}

test("Retry preserves a refused local pin's identity and saved text after its original is discarded", async () => {
  const { openFaultyTab } = await import("../../test/chatApi")
  const { EngineFaults, QuestionFaults } = await import("../../test/faults")
  const root = openTestApp({ answers: false })
  opened.push(root)
  const api = await root.runPromise(Effect.service(TestChatApi))
  const device = nodeDevice({ agent: api })
  const a = openFaultyTab(api, { host: device })
  opened.push(a)
  const chat = await a.runPromise(Effect.service(Chat))
  const store = await a.runPromise(Effect.service(ChatStore))
  store.shown.tanstack.startSyncImmediate(); store.pinned.tanstack.startSyncImmediate()
  await a.runPromise(Effect.flatMap(QuestionFaults, f => f.failNext("bad_request")))
  const asked = (await chat.actions.ask("Keep this refused local copy"))
  if (!asked.asked) throw new Error(asked.reason)
  await until(() => expect(chat.queries.conversation.toArray).toMatchObject([{ status: "unsent" }]))
  await a.runPromise(Effect.flatMap(EngineFaults, f => f.refuseStarts("chat/pin")))
  chat.actions.pin(asked.questionId, true)
  await until(async () => expect((await a.runPromise(store.pinState.pending.toArray))[0]?.failed).toBe(true))
  chat.actions.discardUnsent(asked.questionId)
  await until(() => expect(chat.queries.conversation.toArray).toEqual([]))
  chat.actions.retryPin("home")
  await until(async () => expect((await a.runPromise(store.pinState.pending.toArray))[0]).toMatchObject({ failed: true, awaitAdmission: true, text: "Keep this refused local copy", questionAnswerId: asked.answerId }))
  await a.dispose()
  const restored = await open(api, device)
  restored.actions.retryPin("home")
  await until(() => expect(restored.pin()).toEqual(["Keep this refused local copy"]))
  restored.actions.unpin()
  await until(async () => expect(await restored.runtime.runPromise(restored.store.pinState.pending.toArray)).toEqual([]))
}, 120_000)

test("a first unsent question can be pinned, restored and unpinned before Postgres admits any message", async () => {
  const { openFaultyTab } = await import("../../test/chatApi")
  const { QuestionFaults } = await import("../../test/faults")
  const root = openTestApp({ answers: false })
  opened.push(root)
  const api = await root.runPromise(Effect.service(TestChatApi))
  const device = nodeDevice({ agent: api })
  const first = openFaultyTab(api, { host: device })
  opened.push(first)
  const chat = await first.runPromise(Effect.service(Chat))
  const store = await first.runPromise(Effect.service(ChatStore))
  store.shown.tanstack.startSyncImmediate()
  store.pinned.tanstack.startSyncImmediate()
  await first.runPromise(Effect.flatMap(QuestionFaults, faults => faults.failNext("bad_request")))
  const asked = (await chat.actions.ask("My first unsent question"))
  if (!asked.asked) throw new Error(asked.reason)
  await until(() => expect(chat.queries.conversation.toArray).toMatchObject([{ status: "unsent" }]))
  chat.actions.pin(asked.questionId)
  await until(() => expect(chat.queries.pinned.toArray.map(row => row.text)).toEqual(["My first unsent question"]))
  const [held] = await first.runPromise(store.pinState.pending.toArray)
  expect(held).toMatchObject({ conversationId: "home", awaitAdmission: true, failed: false })
  await until(() => expect(device.stored("message-pin-pending")).toBe(1))
  await first.dispose()
  const restored = await open(api, device)
  await until(() => expect(restored.pin()).toEqual(["My first unsent question"]))
  restored.actions.discardUnsent(asked.questionId)
  await until(() => expect(restored.queries.conversation.toArray).toEqual([]))
  expect(restored.pin()).toEqual(["My first unsent question"])
  restored.actions.unpin()
  await until(() => expect(restored.pin()).toEqual([]))
  await until(async () => expect(await restored.runtime.runPromise(restored.store.pinState.pending.toArray)).toEqual([]))
  const old = await restored.runtime.runPromise(Effect.flatMap(FlowDispatch, dispatch => dispatch.dispatch("chat/pin",
    { messageId: asked.questionId, at: held!.at, awaitAdmission: true, questionAnswerId: asked.answerId }, { door: "button", executionId: `pin:home:${held!.at}` })))
  expect(old).toMatchObject({ _tag: "Done", value: { messageId: null } })
})

test("a queued question pins immediately and follows the person once the question is admitted", async () => {
  const root = openTestApp({ answers: false })
  opened.push(root)
  const api = await root.runPromise(Effect.service(TestChatApi))
  const a = await open(api, nodeDevice({ agent: api }))
  const b = await open(api, nodeDevice({ agent: api }))
  const asked = (await a.actions.ask("Pin my queued question"))
  if (!asked.asked) throw new Error(asked.reason)
  // The queued message control captures local=true before admission removes its asking row.
  const stalePin = () => a.actions.pin(asked.questionId, true)
  a.actions.pin(asked.questionId)
  await until(() => expect(a.pin()).toEqual(["Pin my queued question"]))
  await until(() => expect(b.pin()).toEqual(a.pin()))
  await until(async () => expect(await a.runtime.runPromise(a.store.pinState.pending.toArray)).toEqual([]))
  await until(async () => {
    expect(await a.runtime.runPromise(a.store.asking.toArray)).toEqual([])
    expect(await a.runtime.runPromise(a.store.unsent.toArray)).toEqual([])
  })
  // A callback from the earlier render must leave the synced pin alone: no question or retained intent remains.
  expect(stalePin()).toBeUndefined()
  expect(await a.runtime.runPromise(a.store.pinState.pending.toArray)).toEqual([])
  expect(a.pin()).toEqual(["Pin my queued question"])
  expect(b.pin()).toEqual(a.pin())
  a.actions.unpin()
  await until(() => expect(b.pin()).toEqual([]))
})

test("the person's durable pin follows two devices, stays outside the window, and replaces and unpins", async () => {
  const root = openTestApp({ answers: false }, { people: { other: { subject: { kind: "person", id: "other" }, role: "member" } } })
  opened.push(root)
  const api = await root.runPromise(Effect.service(TestChatApi))
  const device = nodeDevice({ agent: api })
  const a = await open(api, device)
  const b = await open(api, nodeDevice({ agent: api }))
  const otherApi = asPerson(api, "other")
  const c = await open(otherApi, nodeDevice({ agent: otherApi }))
  const asked = (await a.actions.ask("Explain the garden"))
  if (!asked.asked) throw new Error(asked.reason)
  const reply = await root.runPromise(api.answerTo("Explain the garden"))
  reply.say("A garden to discuss."); reply.done()
  await until(() => expect(a.queries.conversation.toArray.at(-1)?.text).toBe("A garden to discuss."))
  // Dispatch never blocks the caller on a network answer.
  expect(a.actions.pin(asked.answerId)).toBeUndefined()
  await until(() => expect(a.pin()).toEqual(["A garden to discuss."]))
  await until(async () => {
    expect(await a.runtime.runPromise(a.store.pinState.pending.toArray)).toEqual([])
    expect(b.pin()).toEqual(a.pin())
  })
  expect(c.pin()).toEqual([])
  a.actions.collapsePin(asked.answerId, true)
  expect(a.queries.pinCollapsed.toArray).toMatchObject([{ id: asked.answerId, collapsed: true }])
  a.actions.collapsePin(asked.answerId, false)
  expect(a.queries.pinCollapsed.toArray[0]?.collapsed).toBe(false)
  const conversationId = (await a.runtime.runPromise(a.store.messages.toArray))[0]!.conversationId!
  // Real later messages push the pinned answer outside the normal 50-message window.
  await root.runPromise(api.branches.run(Effect.flatMap(SqlClient.SqlClient, sql => sql`INSERT INTO messages (id, role, text, status, conversation_id)
    SELECT gen_random_uuid(), 'user', 'Later message ' || i, 'done', ${conversationId} FROM generate_series(1, 60) i`)))
  await until(() => expect(a.queries.conversation.toArray.some(r => r.id === asked.answerId)).toBe(false))
  expect(a.pin()).toEqual(["A garden to discuss."])
  a.actions.pin(asked.questionId)
  await until(() => expect(b.pin()).toEqual(["Explain the garden"]))
  a.actions.unpin()
  await until(() => expect(a.pin()).toEqual([]))
  await until(() => expect(b.pin()).toEqual([]))
  await until(async () => expect(await a.runtime.runPromise(a.store.pinState.pending.toArray)).toEqual([]))
  // An agent call runs the same declaration, resolved against its own answer's conversation.
  const result = await a.runtime.runPromise(Effect.gen(function* () {
    return yield* (yield* FlowDispatch).dispatch("chat/pin", { conversationId: (yield* a.store.messages.toArray)[0]!.conversationId!, messageId: asked.answerId }, { door: "button" })
  }))
  expect(result._tag).toBe("Done")
  await until(() => expect(b.pin()).toEqual(["A garden to discuss."]))
  await until(() => expect(device.stored("message-pins")).toBe(1))
  await a.runtime.dispose()
  const reload = await open(api, device)
  await until(() => expect(reload.pin()).toEqual(["A garden to discuss."]))
  reload.actions.unpin()
  await until(() => expect(b.pin()).toEqual([]))
  expect(c.pin()).toEqual([])
  const Conversations = await import("../../../worker/branch/Conversations")
  const { branch } = await root.runPromise(api.branches.run(Conversations.track("github/octocat/spoon-knife", "pin-branch", "open", "a".repeat(40))))
  await reload.actions.show(branch.conversationId)
  const messageId = crypto.randomUUID()
  await root.runPromise(api.branches.run(Effect.flatMap(SqlClient.SqlClient, sql => sql`INSERT INTO messages (id, role, text, status, conversation_id)
    VALUES (${messageId}, 'user', 'A branch message', 'done', ${branch.conversationId})`)))
  await until(async () => expect((await reload.runtime.runPromise(reload.store.opened(branch.conversationId)!.messages.toArray)).some(r => r.id === messageId)).toBe(true))
  const pinned = reload.queries.of(branch.conversationId).pinned
  pinned.startSyncImmediate()
  reload.actions.pin(messageId)
  await until(() => expect(pinned.toArray.map(r => r.text)).toEqual(["A branch message"]))
  await until(async () => expect(await reload.runtime.runPromise(reload.store.pinState.pending.toArray)).toEqual([]))
  // A message from another conversation is a terminal refusal, not an optimistic saved pin.
  reload.actions.pin(asked.answerId)
  await until(async () => expect((await reload.runtime.runPromise(reload.store.pinState.pending.toArray))[0]!.failed).toBe(true))
  await until(() => expect(pinned.toArray.map(r => r.text)).toEqual(["A branch message"]))
  reload.actions.unpin()
  await until(() => expect(pinned.toArray).toEqual([]))
  await until(async () => expect(await reload.runtime.runPromise(reload.store.pinState.pending.toArray)).toEqual([]))
  await root.runPromise(api.branches.run(Effect.flatMap(SqlClient.SqlClient, sql => sql`DELETE FROM message_pins WHERE conversation_id = ${branch.conversationId}`)))
  await until(async () => expect((await reload.runtime.runPromise(reload.store.pinState.effective.toArray)).some(r => r.conversationId === branch.conversationId)).toBe(false))
  await reload.actions.show(null)
}, 120_000)


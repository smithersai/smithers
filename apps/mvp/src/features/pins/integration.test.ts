test("a late refused pin cannot fail a newer unpin, and a refused unpin remains retryable", async () => {
  const { openFaultyTab } = await import("../../test/chatApi")
  const { EngineFaults } = await import("../../test/faults")
  const root = openTestApp({ answers: false })
  opened.push(root)
  const api = await root.runPromise(Effect.service(TestChatApi))
  const b = await open(api, nodeDevice({ agent: api }))
  const one = await root.runPromise(api.askElsewhere("The synced pin"))
  const two = await root.runPromise(api.askElsewhere("An older pending choice"))
  await until(async () => expect((await b.runtime.runPromise(b.store.messages.toArray)).some(r => r.id === two.questionId)).toBe(true))
  b.actions.pin(one.questionId)
  await until(async () => expect(await b.runtime.runPromise(b.store.pinState.pending.toArray)).toEqual([]))
  const a = openFaultyTab(api, { host: nodeDevice({ agent: api }) })
  opened.push(a)
  const chat = await a.runPromise(Effect.service(Chat))
  const store = await a.runPromise(Effect.service(ChatStore))
  store.pinned.tanstack.startSyncImmediate()
  await until(() => expect(chat.queries.pinned.toArray.map(r => r.id)).toEqual([one.questionId]))
  const faults = await a.runPromise(Effect.service(EngineFaults))
  await a.runPromise(faults.holdStarts)
  chat.actions.pin(two.questionId)
  const [old] = await a.runPromise(store.pinState.pending.toArray)
  chat.actions.unpin()
  const [newer] = await a.runPromise(store.pinState.pending.toArray)
  expect(newer!.at).toBeGreaterThan(old!.at)
  chat.actions.unpin()
  expect((await a.runPromise(store.pinState.pending.toArray))[0]!.at).toBe(newer!.at)
  const locked = Effect.runSync(Deferred.make<void>())
  const release = Effect.runSync(Deferred.make<void>())
  const conversationId = (await b.runtime.runPromise(b.store.messages.toArray))[0]!.conversationId!
  const blocker = root.runFork(api.branches.run(Effect.flatMap(SqlClient.SqlClient, sql => sql.withTransaction(Effect.gen(function* () {
    yield* sql`SELECT * FROM message_pins WHERE conversation_id = ${conversationId} FOR UPDATE`
    yield* Deferred.succeed(locked, undefined)
    yield* Deferred.await(release)
  })))))
  await root.runPromise(Deferred.await(locked))
  try {
    await a.runPromise(faults.refuseResults("chat/pin", "plan_changed"))
    await a.runPromise(faults.releaseStarts)
    const result = await a.runPromise(Effect.flatMap(FlowDispatch, dispatch => dispatch.dispatch("chat/pin",
      { messageId: two.questionId, at: old!.at, awaitAdmission: false },
      { door: "button", executionId: `pin:${old!.conversationId}:${old!.at}` })).pipe(Effect.result))
    expect(result).toMatchObject({ _tag: "Failure", failure: { refusal: "plan_changed" } })
    expect(await a.runPromise(store.pinState.pending.toArray)).toMatchObject([{ at: newer!.at, messageId: null, failed: false }])
  } finally {
    Effect.runSync(Deferred.succeed(release, undefined))
    await root.runPromise(Fiber.join(blocker))
  }
  await until(async () => expect(await a.runPromise(store.pinState.pending.toArray)).toEqual([]))
  await until(() => expect(b.pin()).toEqual([]))
  b.actions.pin(one.questionId)
  await until(() => expect(chat.queries.pinned.toArray.map(r => r.id)).toEqual([one.questionId]))
  await a.runPromise(faults.refuseStarts("chat/unpin"))
  chat.actions.unpin()
  await until(async () => expect((await a.runPromise(store.pinState.pending.toArray))[0]?.failed).toBe(true))
  const [refused] = await a.runPromise(store.pinState.pending.toArray)
  chat.actions.retryPin(refused!.conversationId)
  await until(async () => {
    const [row] = await a.runPromise(store.pinState.pending.toArray)
    expect(row).toMatchObject({ messageId: null, failed: true })
    expect(row!.at).toBeGreaterThan(refused!.at)
  })
  expect(chat.queries.pinned.toArray.map(r => r.id)).toEqual([one.questionId])
}, 120_000)

test("a refused launch rolls the pin back, keeps a retryable intent, and chat stays usable during an unresolved launch", async () => {
  const { openFaultyTab } = await import("../../test/chatApi")
  const { EngineFaults } = await import("../../test/faults")
  const root = openTestApp({ answers: false })
  opened.push(root)
  const api = await root.runPromise(Effect.service(TestChatApi))
  const device = nodeDevice({ agent: api })
  const faulty = openFaultyTab(api, { host: device })
  opened.push(faulty)
  const chat = await faulty.runPromise(Effect.service(Chat))
  const store = await faulty.runPromise(Effect.service(ChatStore))
  store.composerState.tanstack.startSyncImmediate()
  store.pinned.tanstack.startSyncImmediate()
  store.pinState.pendingState.tanstack.startSyncImmediate()
  chat.actions.unpin() // no conversation restored yet
  chat.actions.retryPin("absent")
  const asked = await root.runPromise(api.askElsewhere("A message to pin"))
  await until(async () => expect((await faulty.runPromise(store.messages.toArray)).some(r => r.id === asked.questionId)).toBe(true))
  const conversationId = (await faulty.runPromise(store.messages.toArray))[0]!.conversationId!
  // Postgres permits infinity timestamps. An unreadable sync timestamp must not acknowledge a pending write.
  await root.runPromise(api.branches.run(Effect.flatMap(SqlClient.SqlClient, sql => sql`INSERT INTO message_pins (conversation_id, person_id, message_id, changed_at)
    VALUES (${conversationId}, ${member.subject.id}, NULL, 'infinity')`)))
  await until(async () => expect((await faulty.runPromise(store.pinState.pins.toArray))[0]?.changedAt).toBe("infinity"))
  await faulty.runPromise(Effect.flatMap(EngineFaults, f => f.holdStarts))
  chat.actions.pin(asked.questionId)
  await until(() => expect(chat.queries.pinned.toArray.map(r => r.id)).toEqual([asked.questionId]))
  const firstAt = (await faulty.runPromise(store.pinState.pending.toArray))[0]!.at
  chat.actions.pin(asked.questionId)
  expect((await faulty.runPromise(store.pinState.pending.toArray))[0]!.at).toBe(firstAt)
  chat.actions.setDraft("Keep discussing it")
  expect(chat.queries.composer.toArray[0]?.draft).toBe("Keep discussing it")
  await root.runPromise(api.branches.run(Effect.flatMap(SqlClient.SqlClient, sql => sql`UPDATE message_pins SET changed_at = 'epoch' WHERE conversation_id = ${conversationId}`)))
  await faulty.runPromise(Effect.flatMap(EngineFaults, f => f.releaseStarts))
  await until(async () => expect(await faulty.runPromise(store.pinState.pending.toArray)).toEqual([]))
  chat.actions.unpin()
  await until(async () => expect(await faulty.runPromise(store.pinState.pending.toArray)).toEqual([]))
  await faulty.runPromise(Effect.flatMap(EngineFaults, f => f.refuseStarts("chat/pin")))
  chat.actions.pin(asked.questionId)
  await until(async () => expect((await faulty.runPromise(store.pinState.pending.toArray))[0]?.failed).toBe(true))
  await until(() => expect(chat.queries.pinned.toArray).toEqual([]))
  const at = (await faulty.runPromise(store.pinState.pending.toArray))[0]!.at
  chat.actions.retryPin((await faulty.runPromise(store.pinState.pending.toArray))[0]!.conversationId)
  await until(async () => {
    const [row] = await faulty.runPromise(store.pinState.pending.toArray)
    expect(row!.at).toBeGreaterThan(at)
    expect(row!.failed).toBe(true)
  })
  await faulty.dispose()
  const reloaded = await open(api, device)
  expect(reloaded.pin()).toEqual([])
  const [held] = await reloaded.runtime.runPromise(reloaded.store.pinState.pending.toArray)
  expect(held?.failed).toBe(true)
  reloaded.actions.retryPin(held!.conversationId)
  await until(async () => expect(await reloaded.runtime.runPromise(reloaded.store.pinState.pending.toArray)).toEqual([]))
  expect(reloaded.pin()).toEqual(["A message to pin"])
}, 120_000)

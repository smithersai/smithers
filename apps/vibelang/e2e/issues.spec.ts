test("a lost response resumes the saved issue write without filing it twice", async ({ page }) => {
  const port = Number(process.env.E2E_PORT ?? 4173)
  await page.goto(`http://127.0.0.1:${port}/e2e/runtime/index.html?fault=issue-write`)
  await maintainer(page)
  await page.getByRole("button", { name: "Issues", exact: true }).click()
  await page.getByRole("button", { name: "New issue", exact: true }).click()
  await page.getByRole("textbox", { name: "Title", exact: true }).fill("Only one issue after recovery")
  await page.getByRole("textbox", { name: "Summary", exact: true }).fill("A lost response must retain the write identity.")
  await page.getByRole("button", { name: "New issue", exact: true }).click()
  await expect(page.getByRole("alert")).toContainText("Couldn't save. Retry.")
  await page.keyboard.press("Escape")
  await page.getByRole("button", { name: "Issues", exact: true }).first().click()
  await page.getByRole("button", { name: "Retry", exact: true }).click()
  await expect(page.getByRole("heading", { name: /Only one issue after recovery/ })).toBeVisible()
  await page.getByRole("link", { name: "‹ Issues", exact: true }).click()
  await expect(page.getByRole("link", { name: "Only one issue after recovery", exact: true })).toHaveCount(1)
})


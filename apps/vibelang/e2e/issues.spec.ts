test("a faulty Effect service leaves a retryable error and the real fixture list recovers", async ({ page }) => {
  const port = Number(process.env.E2E_PORT ?? 4173)
  await page.goto(`http://127.0.0.1:${port}/e2e/runtime/index.html?fault=issues`)
  await maintainer(page)
  await page.getByRole("button", { name: "Issues", exact: true }).click()
  await expect(page.getByRole("alert")).toContainText("Couldn't load issues")
  await page.getByRole("button", { name: "Retry", exact: true }).click()
  await expect(page.getByRole("link", { name: "Case branches on tuples", exact: true })).toBeVisible()
  await expect(page.getByRole("alert")).not.toBeVisible()
})


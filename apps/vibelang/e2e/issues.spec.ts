// Playwright collects browser specs only by JS/TS extension.
import { expect, test } from "./coverage"
import type { Page } from "./coverage"

async function maintainer(page: Page) {
  await page.getByRole("combobox", { name: "Visit as" }).selectOption("maintainer")
  await expect(page.locator(".vl-nav-role")).toHaveText("Maintainer")
  await expect(page.getByRole("button", { name: "Account", exact: true })).not.toHaveCSS("background-color", "rgba(0, 0, 0, 0)")
}

test("issues retain their tree and identity when committed, commented and uncommitted", async ({ page }, info) => {
  await page.goto("/?agent=mock")
  await maintainer(page)
  await page.getByRole("button", { name: "Issues", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Issues", exact: true })).toBeVisible()
  await page.getByRole("link", { name: "Case branches on tuples", exact: true }).click()
  await expect(page.getByRole("link", { name: "#38 Effect-native modules" }).first()).toBeVisible()
  await expect(page.getByRole("link", { name: /#49/ })).toBeVisible()
  await expect(page.locator(".sui-item-conv-post")).toContainText("Today only literal values match.")
  await expect(page.locator(".sui-item-conv-comments")).toContainText("Rust lets the binding sit inside the pattern. Worth copying.")
  await page.getByRole("button", { name: "Commit", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "Commit #42 as a task" })
  await expect(dialog).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole("button", { name: "Commit", exact: true })).toBeFocused()
  await page.getByRole("button", { name: "Commit", exact: true }).click()
  await dialog.getByRole("button", { name: "Commit", exact: true }).click()
  await expect(page.getByRole("button", { name: "Uncommit" })).toBeVisible()
  await expect(page.locator(".sui-item-conv-header")).toContainText("Task · Queued")
  await page.getByRole("textbox", { name: "Comment", exact: true }).fill("I can reproduce this with nested tuples.")
  await page.getByRole("textbox", { name: "Comment", exact: true }).press("ControlOrMeta+Enter")
  await expect(page.getByText("I can reproduce this with nested tuples.", { exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath("issue-task.png"), fullPage: true })
  await page.getByRole("button", { name: "Uncommit" }).click()
  await expect(page.getByRole("button", { name: "Commit", exact: true })).toBeVisible()
})


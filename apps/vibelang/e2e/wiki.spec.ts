test("opening Wiki after a long conversation reveals the whole pane above the composer", async ({ page }) => {
  await page.goto("/?agent=mock")
  await page.getByRole("button", { name: "Ask the agent", exact: true }).click()
  for (let index = 0; index < 4; index++) {
    const message = page.getByRole("textbox", { name: "Message", exact: true })
    await message.fill("How do services work?")
    await page.getByRole("button", { name: "Send", exact: true }).click()
    await expect(page.locator('[data-role="assistant"][data-done="true"]')).toHaveCount(index + 1)
  }
  await page.getByRole("button", { name: "Wiki", exact: true }).click()
  await expect(pane(page).getByRole("heading", { name: "VibeLang factory wiki" })).toBeVisible()
  await expect.poll(async () => {
    const box = (await pane(page).boundingBox())!
    const composer = (await page.locator('.sui-chat-composer[data-docked="true"]').boundingBox())!
    return box.y >= 54 && box.y + box.height <= composer.y
  }).toBe(true)
  await pane(page).getByRole("link", { name: "Rulings", exact: true }).first().click()
  await expect(pane(page).getByRole("heading", { name: "Rulings: vibelang.smithers.sh" })).toBeVisible()
  const content = pane(page).locator(".vl-wiki-content")
  await content.focus()
  await expect(content).toBeFocused()
  await page.keyboard.press("End")
  await expect.poll(() => content.evaluate(element => element.scrollTop + element.clientHeight >= element.scrollHeight - 1)).toBe(true)
  await expect(content).toBeFocused()
  await page.keyboard.press("Home")
  await expect.poll(() => content.evaluate(element => element.scrollTop)).toBe(0)
  await expect(pane(page).getByRole("heading", { name: "Rulings: vibelang.smithers.sh" })).toBeInViewport()
})


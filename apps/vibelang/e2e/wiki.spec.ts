// Playwright discovers browser specs only by JS/TS extension.
import { expect, test } from "@playwright/test"
const pane = (page: import("@playwright/test").Page) => page.getByRole("region", { name: "Wiki", exact: true })

test("Wiki opens, navigates real pages, filters, maximizes and returns to chat", async ({ page }, info) => {
  await page.goto("/?agent=mock")
  await page.getByRole("button", { name: "Wiki", exact: true }).click()
  await expect(pane(page).getByRole("heading", { name: "VibeLang factory wiki" })).toBeVisible()
  await expect(pane(page)).toContainText("VL-32")
  await expect(page.getByAltText("The compiler says what to write instead: VibeLang diagnostics with the fix to write")).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Wiki", exact: true })).toHaveCSS("font-weight", "650")
  expect((await pane(page).getByRole("link", { name: "Home", exact: true }).boundingBox())!.height).toBeGreaterThanOrEqual(24)
  await expect(page.getByRole("button", { name: "Edit", exact: true })).toHaveCount(0)
  await pane(page).getByRole("link", { name: "Rulings", exact: true }).first().click()
  await expect(page).toHaveURL(/\/wiki\/rulings/)
  await expect(pane(page).getByRole("heading", { name: "Rulings: vibelang.smithers.sh" })).toBeVisible()
  await pane(page).getByRole("link", { name: "0014 agent-tour", exact: true }).click()
  await expect(pane(page)).toContainText("Accepted")
  await pane(page).getByRole("button", { name: "VL-28", exact: true }).click()
  await expect(page).toHaveURL(/\/wiki\/rulings(?:\?[^#]*)?#vl-28/)
  await expect(pane(page).locator("#vl-28")).toBeInViewport()
  await page.goBack()
  await expect(pane(page).getByRole("heading", { name: /0014/ })).toBeVisible()
  await pane(page).getByRole("button", { name: "Maximize the wiki" }).click()
  await expect(pane(page)).toHaveAttribute("data-maximized", "true")
  const box = (await pane(page).boundingBox())!
  expect(box.width).toBe(page.viewportSize()!.width)
  const header = (await page.getByRole("banner").boundingBox())!
  expect(box.y).toBeGreaterThanOrEqual(header.y + header.height)
  await pane(page).getByRole("button", { name: "Minimize the wiki" }).click()
  await expect(pane(page)).toHaveAttribute("data-maximized", "false")
  await pane(page).getByRole("button", { name: "Maximize the wiki" }).click()
  await page.keyboard.press("Escape")
  await expect(pane(page)).toHaveAttribute("data-maximized", "false")
  await pane(page).getByRole("textbox", { name: "Find a page" }).fill("zebra")
  await expect(pane(page)).toContainText('No pages match "zebra"')
  await pane(page).getByRole("textbox", { name: "Find a page" }).fill("")
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const composer = await page.locator('.sui-chat-composer[data-docked="true"]').boundingBox()
  const wiki = await pane(page).boundingBox()
  expect(wiki!.y + wiki!.height).toBeLessThanOrEqual(composer!.y)
  await page.screenshot({ path: info.outputPath("wiki.png") })
})


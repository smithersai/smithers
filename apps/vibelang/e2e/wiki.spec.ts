test("Wiki takes the foreground from a maximized sandbox and keeps both panes usable", async ({ page }) => {
  await page.goto("/?agent=mock")
  await page.getByRole("button", { name: "Wiki", exact: true }).click()
  await expect(pane(page).getByRole("heading", { name: "VibeLang factory wiki" })).toBeVisible()
  await page.getByRole("button", { name: "Sandboxes", exact: true }).click()
  const sandboxes = page.getByRole("region", { name: "Sandboxes", exact: true })
  await sandboxes.getByRole("button", { name: "Maximize Sandboxes" }).click()
  await expect(sandboxes).toHaveAttribute("data-maximized", "true")
  await page.getByRole("button", { name: "Wiki", exact: true }).click()
  await expect(sandboxes).toHaveAttribute("data-maximized", "false")
  await expect(pane(page).getByRole("heading", { name: "VibeLang factory wiki" })).toBeVisible()
  await pane(page).getByRole("button", { name: "Maximize the wiki" }).click()
  await expect(pane(page)).toHaveAttribute("data-maximized", "true")
  await page.keyboard.press("ControlOrMeta+k")
  const prompt = page.getByRole("dialog", { name: "Ask the agent" })
  await prompt.getByRole("textbox", { name: "Message", exact: true }).fill("/sandbox")
  await prompt.getByRole("button", { name: "Send", exact: true }).click()
  await expect(prompt).not.toBeVisible()
  await expect(page.locator("#vl-wiki")).toHaveAttribute("data-maximized", "false")
  await expect(sandboxes).toHaveAttribute("data-maximized", "true")
})

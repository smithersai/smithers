// Stays .ts: Playwright collects browser tests by JS/TS extension only.
// Inputs the page accepts and does nothing with, and reads that fail where the person is not looking.
import { expect, test, type Page } from "./coverage"

const port = Number(process.env.E2E_PORT ?? 4173)
const faulted = (page: Page) => page.evaluate(() => (window as unknown as { recovery: { snapshot(): { faulted: boolean } } }).recovery.snapshot().faulted)

test("an unknown slash command and an empty terminal line send nothing", async ({ page }) => {
  await page.goto("/?agent=mock&role=contributor")
  await page.getByRole("button", { name: "Ask the agent", exact: true }).click()
  const prompt = page.getByRole("dialog", { name: "Ask the agent" })
  const message = prompt.getByRole("textbox", { name: "Message", exact: true })
  await message.fill("/nothing-here")
  await message.press("Enter")
  await expect(prompt).toBeVisible()
  await expect(message).toHaveValue("/nothing-here")
  await message.fill("/sandbox")
  await message.press("Enter")
  await expect(page.getByRole("status", { name: "Sandbox" })).toHaveText("Running")
  const command = page.getByRole("textbox", { name: "Terminal command" })
  await expect(command).toBeEnabled()
  await command.press("Enter")
  await expect(command).toBeEnabled()
  await expect(page.getByLabel("Terminal output")).not.toContainText("$")
})

test("an issue count that fails to load in chat leaves the Issues button working", async ({ page }) => {
  await page.goto(`http://127.0.0.1:${port}/e2e/runtime/index.html?fault=issues`)
  await page.getByRole("button", { name: "Ask the agent", exact: true }).click()
  await page.getByRole("dialog").getByRole("textbox", { name: "Message", exact: true }).fill("Hello")
  await page.getByRole("dialog").getByRole("button", { name: "Send", exact: true }).click()
  await expect(page.getByRole("log", { name: "Conversation" })).toBeVisible()
  await expect.poll(() => faulted(page)).toBe(true)
  await page.getByRole("button", { name: "Issues", exact: true }).first().click()
  await expect(page.getByRole("link", { name: "Case branches on tuples", exact: true })).toBeVisible()
})

test("an account that fails to load says sign-in failed, and Retry signs in", async ({ page }) => {
  await page.goto(`http://127.0.0.1:${port}/e2e/runtime/index.html?fault=account-read`)
  const alert = page.getByRole("alert")
  await expect(alert).toContainText("Sign-in failed. GitHub didn’t answer.")
  await alert.getByRole("button", { name: "Retry", exact: true }).click()
  await expect(alert).toHaveCount(0)
  await expect(page.getByRole("combobox", { name: "Visit as" })).toHaveValue("new")
})

test("a JSON command run with an empty input says the input isn't valid", async ({ page }) => {
  await page.goto("/?agent=mock")
  await page.getByRole("combobox", { name: "Visit as" }).selectOption("maintainer")
  await expect(page.locator(".vl-nav-role")).toHaveText("Maintainer")
  await page.getByRole("button", { name: "Ask the agent", exact: true }).click()
  await page.getByRole("dialog").getByRole("textbox", { name: "Message", exact: true }).fill("Hello")
  await page.getByRole("dialog").getByRole("button", { name: "Send", exact: true }).click()
  await page.getByRole("button", { name: "Expand Actions", exact: true }).click()
  const pane = page.getByRole("region", { name: "Actions", exact: true })
  await pane.getByRole("button", { name: "Note", exact: true }).click()
  await pane.getByRole("button", { name: "Run", exact: true }).click()
  await expect(pane.getByRole("alert")).toContainText("Input isn't valid.")
})

test("a slash command sent while a run is starting starts nothing", async ({ page }) => {
  await page.goto(`http://127.0.0.1:${port}/e2e/runtime/index.html?fault=held-start`)
  await page.getByRole("combobox", { name: "Visit as" }).selectOption("maintainer")
  await expect(page.locator(".vl-nav-role")).toHaveText("Maintainer")
  await page.keyboard.press("ControlOrMeta+k")
  const prompt = page.getByRole("dialog").getByRole("textbox", { name: "Message", exact: true })
  await prompt.fill("Hello")
  await prompt.press("Enter")
  await page.getByRole("button", { name: "Expand Actions", exact: true }).click()
  const pane = page.getByRole("region", { name: "Actions", exact: true })
  await pane.getByRole("button", { name: "Tour", exact: true }).click()
  await pane.getByRole("button", { name: "Run", exact: true }).click()
  const input = page.locator('form[data-docked="true"]').getByRole("textbox", { name: "Message", exact: true })
  await input.fill("/post What is a tuple?")
  await input.press("Enter")
  await page.evaluate(() => (window as unknown as { recovery: { release(): unknown } }).recovery.release())
  await expect.poll(() => faulted(page)).toBe(true)
  await expect(page.getByRole("button", { name: /Open Tour run/ })).toHaveCount(1)
  await expect(page.getByRole("button", { name: /Open Post run/ })).toHaveCount(0)
})

test("the agent answers an unknown command as unavailable", async ({ page }) => {
  await page.goto("/?agent=mock")
  await page.getByRole("button", { name: "Ask the agent", exact: true }).click()
  await page.getByRole("dialog").getByRole("textbox", { name: "Message", exact: true }).fill("Run /nothing-here")
  await page.getByRole("dialog").getByRole("button", { name: "Send", exact: true }).click()
  const answer = page.locator(".sui-chat-message[data-role='assistant']").last()
  await expect(answer).toHaveAttribute("data-done", "true")
  await expect(answer).toContainText("Action unavailable.")
})

test("a maintainer confirms promotions and demotions and can cancel", async ({ page }) => {
  await page.goto("/?agent=mock")
  await page.getByRole("combobox", { name: "Visit as" }).selectOption("maintainer")
  await page.getByRole("button", { name: "Account", exact: true }).click()
  await page.getByRole("menuitem", { name: "People" }).click()
  const newcomer = page.getByRole("combobox", { name: "Role for joss" })
  await newcomer.selectOption("community")
  await page.getByRole("dialog", { name: "Promote joss to Community?" }).getByRole("button", { name: "Promote", exact: true }).click()
  await expect(newcomer).toHaveValue("community")
  const person = page.getByRole("combobox", { name: "Role for rira" })
  for (const role of ["maintainer", "contributor", "community", "contributor"]) {
    await person.selectOption(role)
    const dialog = page.getByRole("dialog", { name: new RegExp("rira to " + role[0]!.toUpperCase() + role.slice(1)) })
    await expect(dialog).toBeVisible()
    await dialog.getByRole("button", { name: /^(Promote|Demote)$/ }).click()
    await expect(dialog).not.toBeVisible()
    await expect(person).toHaveValue(role)
  }
  await person.selectOption("maintainer")
  await page.getByRole("button", { name: "Cancel", exact: true }).click()
  await expect(person).toHaveValue("contributor")
})

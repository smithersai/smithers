// Stays .ts: Playwright collects browser tests by JS/TS extension only.
import { expect, test } from "@playwright/test"

test("every role's view works without a backend", async ({ page }, testInfo) => {
  await page.goto("/?agent=mock")
  const picker = page.getByRole("combobox", { name: "Visit as" })
  await expect(picker).toBeVisible()
  for (const role of ["viewer", "new", "community", "contributor", "maintainer"]) {
    await picker.selectOption(role)
    if (role === "viewer") await expect(page.getByRole("button", { name: "Sign in", exact: true })).toBeVisible()
    else {
      await expect(page.getByRole("button", { name: "Account", exact: true })).toBeVisible()
      await page.getByRole("button", { name: "Account", exact: true }).click()
      await expect(page.getByRole("menu", { name: "Account menu" })).toBeVisible()
      await page.getByRole("menuitem", { name: "People" }).click()
      await expect(page.getByRole("region", { name: "People" })).toBeVisible()
      if (role !== "maintainer") await expect(page.getByRole("combobox", { name: /^Role for/ })).toHaveCount(0)
      await page.screenshot({ path: testInfo.outputPath("people-" + role + ".png") })
      await page.getByRole("button", { name: "Close People" }).click()
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
    await page.screenshot({ path: testInfo.outputPath("role-" + role + ".png") })
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width)
})
test("a maintainer confirms promotions and demotions and can cancel", async ({ page }) => {
  await page.goto("/?agent=mock")
  await page.getByRole("combobox", { name: "Visit as" }).selectOption("maintainer")
  await page.getByRole("button", { name: "Account", exact: true }).click()
  await page.getByRole("menuitem", { name: "People" }).click()
  const newcomer = page.getByRole("combobox", { name: "Role for joss" })
  await newcomer.selectOption("community")
  await page.getByRole("dialog", { name: "Promote joss to Community?" }).getByRole("button", { name: "Promote", exact: true }).click()
  await expect(newcomer).toHaveValue("community")
  const person = page.getByRole("combobox", { name: "Role for rira" })
  for (const role of ["maintainer", "contributor", "community", "contributor"]) {
    await person.selectOption(role)
    const dialog = page.getByRole("dialog", { name: new RegExp("rira to " + role[0]!.toUpperCase() + role.slice(1)) })
    await expect(dialog).toBeVisible()
    await dialog.getByRole("button", { name: /^(Promote|Demote)$/ }).click()
    await expect(dialog).not.toBeVisible()
    await expect(person).toHaveValue(role)
  }
  await person.selectOption("maintainer")
  await page.getByRole("button", { name: "Cancel", exact: true }).click()
  await expect(person).toHaveValue("contributor")
})
test("a new person's first accepted post earns Community", async ({ page }) => {
  await page.goto("/?agent=mock")
  await page.getByRole("combobox", { name: "Visit as" }).selectOption("new")
  await page.getByRole("button", { name: "Ask the agent", exact: true }).click()
  const prompt = page.getByRole("dialog", { name: "Ask the agent" })
  await prompt.getByRole("textbox", { name: "Message" }).fill("How do I install it?")
  await prompt.getByRole("button", { name: "Send" }).click()
  await expect(page.getByText("You're now Community.", { exact: true })).toBeVisible()
  await expect(page.getByRole("combobox", { name: "Visit as" })).toHaveValue("community")
})

test("account menu and promotion dialog support the keyboard", async ({ page }) => {
  await page.goto("/?agent=mock")
  await page.getByRole("combobox", { name: "Visit as" }).selectOption("maintainer")
  const account = page.getByRole("button", { name: "Account", exact: true })
  await account.focus()
  await page.keyboard.press("Enter")
  await expect(page.getByRole("menuitem", { name: "People" })).toBeFocused()
  await page.keyboard.press("ArrowDown")
  await expect(page.getByRole("menuitem", { name: "Sign out" })).toBeFocused()
  await page.keyboard.press("Escape")
  await expect(account).toBeFocused()
  await expect(page.getByRole("menu", { name: "Account menu" })).toHaveCount(0)
  await account.press("Enter")
  await page.getByRole("menuitem", { name: "People" }).press("Enter")
  await page.getByRole("combobox", { name: "Role for rira" }).selectOption("maintainer")
  await expect(page.getByRole("button", { name: "Cancel", exact: true })).toBeFocused()
  await page.keyboard.press("Escape")
  await expect(page.getByRole("dialog", { name: "Promote rira to Maintainer?" })).not.toBeVisible()
})

test("a failed callback displays a retryable sign-in notice", async ({ page }) => {
  await page.goto("/?agent=mock&sign-in=failed")
  await expect(page.getByRole("alert")).toContainText("Sign-in failed.")
  await page.getByRole("button", { name: "Retry", exact: true }).click()
  await expect(page.getByRole("button", { name: "Account", exact: true })).toBeVisible()
  await expect(page.getByRole("alert")).toHaveCount(0)
})

test("Escape takes back the tour before closing an open account menu", async ({ page }) => {
  await page.goto("/?agent=mock")
  await page.getByRole("combobox", { name: "Visit as" }).selectOption("maintainer")
  await page.getByRole("button", { name: "Learn more", exact: true }).click()
  const narration = page.locator(".sui-chat-message[data-role='assistant'][data-in-reply-to='']")
  await expect(narration).toContainText("VibeLang is")
  await page.getByRole("button", { name: "Account", exact: true }).click()
  const menu = page.getByRole("menu", { name: "Account menu" })
  await expect(menu).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(page.locator(".vl-glow")).toBeHidden()
  await expect(narration).toHaveAttribute("data-done", "true")
  await expect(menu).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(menu).not.toBeVisible()
})

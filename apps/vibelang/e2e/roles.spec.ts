test("account menu and promotion dialog support the keyboard", async ({ page }) => {
  await page.goto("/?agent=mock")
  await page.getByRole("combobox", { name: "Visit as" }).selectOption("maintainer")
  const account = page.getByRole("button", { name: "Account", exact: true })
  await account.focus()
  await page.keyboard.press("Enter")
  await expect(page.getByRole("menuitem", { name: "People" })).toBeFocused()
  await page.keyboard.press("ArrowDown")
  await expect(page.getByRole("menuitem", { name: "Sign out" })).toBeFocused()
  await page.keyboard.press("Escape")
  await expect(account).toBeFocused()
  await expect(page.getByRole("menu", { name: "Account menu" })).toHaveCount(0)
  await account.press("Enter")
  await page.getByRole("menuitem", { name: "People" }).press("Enter")
  await page.getByRole("combobox", { name: "Role for rira" }).selectOption("maintainer")
  await expect(page.getByRole("button", { name: "Cancel", exact: true })).toBeFocused()
  await page.keyboard.press("Escape")
  await expect(page.getByRole("dialog", { name: "Promote rira to Maintainer?" })).not.toBeVisible()
})


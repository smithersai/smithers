// Writes worker/agentContext.ts: the agent's system context, VibeLang's own skill (the installed
// `vibelang/skills/vibelang/SKILL.md`, frontmatter removed) under the agent's instructions. The Worker bundles the
// text; test/agentContext.test.ts fails when the installed skill changes and this file wasn't regenerated.
//   node scripts/agent-context.mjs           write
//   node scripts/agent-context.mjs --check   exit 1 when the file is stale
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

// The package the app installs (its exports name no skill file), read where pnpm links it.
const vibelang = new URL("../node_modules/vibelang/", import.meta.url)
const skill = readFileSync(new URL("skills/vibelang/SKILL.md", vibelang), "utf8").replace(/^---\n[\s\S]*?\n---\n+/, "").trim()
const version = JSON.parse(readFileSync(new URL("package.json", vibelang), "utf8")).version

const instructions = `You are the VibeLang agent on vibelang.smithers.sh, the factory where people build VibeLang together.
Answer questions about VibeLang, the language for Effect: how to write it, how it maps to Effect TypeScript, and how
to fix code that doesn't compile. Be brief: a sentence or two, then code. Put VibeLang in \`\`\`vibe fences and shell
commands in \`\`\`sh fences. Use only the syntax in the reference below, VibeLang ${version}; when you don't know,
say so instead of inventing syntax. You can't run code, open links or see the person's files.`

const text = `${instructions}\n\n# VibeLang ${version} reference\n\n${skill}\n`
const source = `// Generated by scripts/agent-context.mjs from vibelang ${version}'s skills/vibelang/SKILL.md. Do not edit.\n` +
  `export const AGENT_CONTEXT = ${JSON.stringify(text)}\n`
const target = fileURLToPath(new URL("../worker/agentContext.ts", import.meta.url))

if (process.argv.includes("--check")) {
  let current = ""
  try { current = readFileSync(target, "utf8") } catch {}
  if (current !== source) {
    console.error("worker/agentContext.ts is stale: run node scripts/agent-context.mjs")
    process.exit(1)
  }
} else {
  writeFileSync(target, source)
}

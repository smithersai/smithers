/**
 * Renders the CLI reference at smithers.sh/docs/reference/cli/ and its
 * Markdown copy at /docs/reference/cli.md from what gen-cli-data.mjs captures
 * from the checked-out CLI: the command manifest (src/data/cli-commands.json,
 * `smthrs --llms-full --format json`) and each command's `--help`
 * (src/data/help/). Command descriptions, usage lines, types and option
 * defaults are the CLI's own; TUI budget guidance comes from its colocated
 * docs. Option spellings and aliases
 * come from the help; types, defaults and descriptions come from the schema.
 * A command, argument or option that one source has and the other lacks, or a
 * schema keyword this script cannot render, throws instead of being skipped.
 * Check mode compares bytes.
 *
 * Required means the command refuses to run without the value: the schema
 * lists it as required and gives it no default. A default makes the decoded
 * field required in the schema, but a person never has to pass it.
 *
 * Usage: node apps/site/scripts/gen-cli-reference.mjs [--check]
 *
 * @since 1.0.0
 */
import { existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const site = resolve(import.meta.dirname, "..")
const root = resolve(site, "../..")
const script = "apps/site/scripts/gen-cli-reference.mjs"

/** The comment the page opens its frontmatter with. */
export const MARKER = `# GENERATED by ${script} from src/data/cli-commands.json and src/data/help. Do not edit.`
/** The Starlight page, by repository path. */
export const PAGE = "apps/site/src/content/docs/docs/reference/cli.md"
/** The Markdown copy, by repository path. */
export const COPY = "apps/site/public/docs/reference/cli.md"

const TITLE = "CLI reference"
const DESCRIPTION = "Install discovery and additional local commands, with usage, arguments, options and defaults from the CLI's own help."
const INSTALL = "npm install -g smthrs@next"
const COLUMNS = ["Type", "Default", "Required", "Description"]

/** The schema keywords `typeOf` renders; any other keyword throws. */
const KEYWORDS = new Set([
  "type", "description", "default", "enum", "items", "anyOf", "pattern", "minLength", "maxLength",
  "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "minItems", "maxItems", "properties",
  "additionalProperties", "required"
])
const CONSTRAINTS = [
  ["pattern", (value) => `pattern ${code(value)}`],
  ["minLength", (value) => `min length ${value}`],
  ["maxLength", (value) => `max length ${value}`],
  ["minimum", (value) => `minimum ${value}`],
  ["exclusiveMinimum", (value) => `greater than ${value}`],
  // Effect encodes every integer with this bound; it is no limit a command sets.
  ["maximum", (value) => (value === Number.MAX_SAFE_INTEGER ? undefined : `maximum ${value}`)],
  ["exclusiveMaximum", (value) => `less than ${value}`],
  ["minItems", (value) => `min items ${value}`],
  ["maxItems", (value) => `max items ${value}`]
]
const OPTION = /^ {2}(-{1,2}[^\s,<]+(?:, -{1,2}[^\s,<]+)*)(?: <([^>]+)>)?(?: {2,}(.*))?$/
const ARGUMENT = /^ {2}(\S+)(?: {2,}(.*))?$/

const kebab = (name) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)
const escapeRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")

/** Inline code that survives any backtick in the value. */
function code(value) {
  const text = String(value)
  return text.includes("`") ? `\`\` ${text} \`\`` : `\`${text}\``
}

/** CLI text as literal Markdown: no emphasis, link, code or HTML it did not mean. */
export function prose(text) {
  return text
    .replace(/[\\`*[\]<]/g, "\\$&")
    .replace(/(?<![\p{L}\p{N}])_|_(?![\p{L}\p{N}])/gu, "\\_")
    .replace(/&(?=#?[A-Za-z0-9]+;)/g, "&amp;")
    .replace(/(?<![\w\\])--[a-z][a-z0-9-]*/gi, code)
}

/** A paragraph that cannot open a heading, quote or list. */
const paragraph = (text) => prose(text).replace(/^(?=[#>+-])/, "\\").replace(/^(\d+)([.)])/, "$1\\$2")

/** A table whose cells keep their pipes. */
function table(head, rows) {
  const line = (cells) => `| ${cells.map((cell) => cell.replaceAll("|", "\\|")).join(" | ")} |`
  return [line(head), line(head.map(() => "---")), ...rows.map(line)].join("\n")
}

/** The type a schema accepts, its constraints appended, `null` dropped from unions. */
export function typeOf(schema, where) {
  for (const key of Object.keys(schema)) {
    if (!KEYWORDS.has(key)) throw new Error(`${where}: schema keyword ${key} has no rendering`)
  }
  let base
  if (schema.anyOf !== undefined) {
    const branches = schema.anyOf.map((branch) => typeOf(branch, where)).filter((type) => type !== "null")
    base = branches.length === 0 ? "null" : branches.join(" or ")
  } else if (schema.enum !== undefined) {
    base = `one of ${schema.enum.map(code).join(", ")}`
  } else {
    if (schema.type === undefined) throw new Error(`${where}: schema has no type`)
    const types = [schema.type].flat()
    const named = types.filter((type) => type !== "null")
      .map((type) => (type === "array" ? `array of ${schema.items === undefined ? "any" : typeOf(schema.items, where)}` : type))
    base = named.length === 0 ? "null" : named.join(" or ")
  }
  const constraints = CONSTRAINTS.flatMap(([key, render]) => (schema[key] === undefined ? [] : [render(schema[key])]))
    .filter((constraint) => constraint !== undefined)
  return [base, ...constraints].join(", ")
}

/** A default as the reader types it: strings bare, everything else as JSON. */
const defaultOf = (schema) =>
  !("default" in schema) ? "" : code(typeof schema.default === "string" && schema.default !== "" ? schema.default : JSON.stringify(schema.default))

/** A help capture's description, usage line and labelled sections. */
export function parseHelp(text, name) {
  const lines = text.replace(/\r\n/g, "\n").split("\n")
  const head = new RegExp(`^${escapeRegExp(name)}(?:@(\\S+))? — (.+)$`).exec(lines[0])
  if (!head) throw new Error(`help for ${name}: first line ${JSON.stringify(lines[0])} is not "${name} — <description>"`)
  const sections = new Map()
  let usage
  let current
  for (const line of lines.slice(1)) {
    const label = /^([A-Z][A-Za-z ]*):$/.exec(line)
    if (line.startsWith("Usage: ")) {
      if (usage !== undefined) throw new Error(`help for ${name}: more than one usage line`)
      usage = line.slice("Usage: ".length)
      current = undefined
    } else if (label) {
      current = []
      sections.set(label[1], current)
    } else if (line.startsWith("  ") && current) current.push(line)
    else if (line.trim() === "") current = undefined
    else throw new Error(`help for ${name}: unexpected line ${JSON.stringify(line)}`)
  }
  if (usage === undefined) throw new Error(`help for ${name}: no usage line`)
  return { version: head[1], description: head[2], usage, sections }
}

/** The options a help section lists, keyed by first spelling. */
function helpOptions(lines, where) {
  return new Map(lines.map((line) => {
    const match = OPTION.exec(line)
    if (!match) throw new Error(`${where}: option line ${JSON.stringify(line)} does not parse`)
    const names = match[1].split(", ")
    return [names[0], { names, value: match[2], description: match[3] ?? "" }]
  }))
}

/** Option rows: spellings from the help, everything else from the schema. */
function optionRows(object, lines, where) {
  const listed = helpOptions(lines, where)
  const required = new Set(object?.required ?? [])
  const rows = Object.entries(object?.properties ?? {}).map(([key, schema]) => {
    const flag = `--${kebab(key)}`
    const help = listed.get(flag)
    if (!help) throw new Error(`${where}: the schema has option ${key}, but the help lists no ${flag}`)
    listed.delete(flag)
    return [
      help.names.map(code).join(", "),
      typeOf(schema, `${where} ${flag}`),
      defaultOf(schema),
      required.has(key) && !("default" in schema) ? "yes" : "no",
      prose(schema.description ?? "")
    ]
  })
  if (listed.size > 0) throw new Error(`${where}: the help lists ${[...listed.keys()].join(", ")}, which the schema lacks`)
  return rows
}

/** Argument rows, in the order the help and the schema both list them. */
function argumentRows(object, lines, where) {
  const listed = lines.map((line) => {
    const match = ARGUMENT.exec(line)
    if (!match) throw new Error(`${where}: argument line ${JSON.stringify(line)} does not parse`)
    return match[1]
  })
  const names = Object.keys(object?.properties ?? {})
  if (listed.join(" ") !== names.join(" ")) {
    throw new Error(`${where}: the help lists arguments [${listed.join(", ")}], the schema [${names.join(", ")}]`)
  }
  const required = new Set(object?.required ?? [])
  return names.map((name) => {
    const schema = object.properties[name]
    return [
      code(name),
      typeOf(schema, `${where} <${name}>`),
      defaultOf(schema),
      required.has(name) && !("default" in schema) ? "yes" : "no",
      prose(schema.description ?? "")
    ]
  })
}

/** The heading anchor Starlight and check-docs give a command heading. */
const anchor = (name) => name.replaceAll(" ", "-")

/**
 * The page body: purpose, install, the command table, the global options, then
 * one `##` section per top-level command and one `###` per subcommand.
 * `help(path)` returns the capture for a command path ("" is `smthrs` itself)
 * or undefined.
 */
export function renderBody({ manifest, help, additional = [], notes = {}, integrations = [] }) {
  if (!Array.isArray(manifest.commands) || manifest.commands.length === 0) throw new Error("cli-commands.json lists no commands")
  const capture = (path) => {
    const text = help(path)
    const name = path === "" ? "smthrs" : `smthrs ${path}`
    if (text === undefined) throw new Error(`no help capture for ${name}`)
    return parseHelp(text, name)
  }
  const top = capture("")
  if (top.version === undefined) throw new Error("help for smthrs: the first line names no version")
  const globals = top.sections.get("Custom Global Options") ?? []

  const commands = [...new Map([...manifest.commands, ...additional].map(command => [command.name, command])).values()]
  const leaves = new Map(commands.map((command) => [command.name, command]))
  const groups = new Map()
  for (const command of commands) {
    const [group] = command.name.split(" ")
    if (!groups.has(group)) groups.set(group, [])
    if (command.name !== group) groups.get(group).push(command.name)
  }
  const seen = new Set(["commands", "global-options"])
  const claim = (name) => {
    if (seen.has(anchor(name))) throw new Error(`two headings share the anchor #${anchor(name)}`)
    seen.add(anchor(name))
  }

  const section = (level, path) => {
    claim(path)
    const where = `smthrs ${path}`
    const text = capture(path)
    if ((text.sections.get("Custom Global Options") ?? []).join("\n") !== globals.join("\n")) {
      throw new Error(`${where}: its help lists different global options than smthrs --help`)
    }
    const command = leaves.get(path)
    if (command && command.description !== text.description) {
      throw new Error(`${where}: the manifest says ${JSON.stringify(command.description)}, the help ${JSON.stringify(text.description)}`)
    }
    const parts = [`${"#".repeat(level)} ${code(path)}`, paragraph(text.description), "```text\n" + text.usage + "\n```"]
    if (command) {
      const args = argumentRows(command.schema?.args, text.sections.get("Arguments") ?? [], where)
      const options = optionRows(command.schema?.options, text.sections.get("Options") ?? [], where)
      if (args.length > 0) parts.push(table(["Argument", ...COLUMNS], args))
      if (options.length > 0) parts.push(table(["Option", ...COLUMNS], options))
    } else if (text.sections.has("Arguments") || text.sections.has("Options")) {
      throw new Error(`${where}: the help lists arguments or options, but the manifest has no such command`)
    }
    if (notes[path] !== undefined) parts.push(notes[path].trim())
    return parts.join("\n\n")
  }

  const builtIn = helpOptions(top.sections.get("Global Options") ?? [], "smthrs --help")
  return [
    `Install discovery for ${code("smthrs")} ${top.version}, plus additional local commands, as their ${code("--help")} describes them.`,
    "Other callable library commands stay outside install discovery. Use their explicit `--help`; see the [library command reference](https://github.com/smithersai/smithers/blob/main/packages/smithers/docs/reference/cli/README.md) and [CLI API](/docs/reference/api/cli/).",
    "```bash\n" + INSTALL + "\n```",
    "## Commands",
    table(["Command", "Description"], [...groups.keys()].map((group) => [`[${code(group)}](#${anchor(group)})`, prose(capture(group).description)])),
    "## Global options",
    "Every command takes these options.",
    table(["Option", ...COLUMNS], optionRows(manifest.globals, globals, "smthrs global options")),
    `${code("smthrs --help")} also lists these built-in options.`,
    table(["Option", "Value", "Description"], [...builtIn.values()].map(({ names, value, description }) =>
      [names.map(code).join(", "), value === undefined ? "" : code(value), prose(description)])),
    ...[...groups].map(([group, subcommands]) => [section(2, group), ...subcommands.map((path) => section(3, path))].join("\n\n")),
    ...integrations.map(({ name, captures }) => {
      claim(name)
      return [`## ${code(name)}`, ...captures.map(text => "```text\n" + text.trim() + "\n```")].join("\n\n")
    })
  ].join("\n\n") + "\n"
}

/** The Starlight page around a body. */
export const sitePage = (body) => [
  "---",
  MARKER,
  `editUrl: https://github.com/smithersai/smithers/edit/main/${script}`,
  `title: ${JSON.stringify(TITLE)}`,
  `description: ${JSON.stringify(DESCRIPTION)}`,
  "head:",
  "  - tag: link",
  "    attrs:",
  "      rel: alternate",
  "      type: text/markdown",
  `      href: ${COPY.replace("apps/site/public", "")}`,
  "---",
  "",
  body
].join("\n")

/** The Markdown copy around a body, shaped like the app pages' copies. */
export const markdownCopy = (body) => `# ${TITLE}\n\n> ${DESCRIPTION}\n\n${body}`

/** Both files, by repository path, rendered from the committed captures. */
export function projection(directory = root) {
  const data = join(directory, "apps/site/src/data")
  const manifest = JSON.parse(readFileSync(join(data, "cli-commands.json"), "utf8"))
  const help = (path) => {
    const tokens = path === "" ? ["smthrs"] : path.split(" ")
    const file = join(data, "help", ...tokens.slice(0, -1), `${tokens.at(-1)}.txt`)
    return existsSync(file) ? readFileSync(file, "utf8") : undefined
  }
  const extra = join(data, "cli-reference-extra.json")
  const additional = existsSync(extra) ? JSON.parse(readFileSync(extra, "utf8")) : []
  const notes = additional.some(command => command.name === "tui")
    ? { tui: readFileSync(join(directory, "packages/smithers/docs/reference/cli/tui.md"), "utf8") } : {}
  const integrations = [
    ["completions"], ["mcp", "mcp add", "mcp doctor"], ["skills", "skills add", "skills list"]
  ].filter(paths => help(paths[0]) !== undefined).map(paths => ({
    name: paths[0],
    captures: paths.map(path => {
      const text = help(path)
      if (text === undefined) throw new Error(`no integration help capture for smthrs ${path}`)
      return text
    })
  }))
  const body = renderBody({ manifest, help, additional, notes, integrations })
  return new Map([[PAGE, sitePage(body)], [COPY, markdownCopy(body)]])
}

/** Execute the generator against a concrete output projection and directory. */
export function main(argv = process.argv, { directory = root, files } = {}) {
  // realpath: a module URL names the resolved file.
  if (argv[1] && realpathSync(argv[1]) === fileURLToPath(import.meta.url)) {
    const check = argv.includes("--check")
    let drift = 0
    for (const [path, content] of files ?? projection(directory)) {
      const target = join(directory, path)
      const current = existsSync(target) ? readFileSync(target, "utf8") : undefined
      if (current === content) continue
      drift++
      if (check) console.error(`cli reference drift: ${path} ${current === undefined ? "is missing" : "differs"}`)
      else {
        mkdirSync(dirname(target), { recursive: true })
        writeFileSync(target, content)
        console.log(`wrote ${path}`)
      }
    }
    if (check && drift > 0) {
      console.error(`cli reference: ${drift} file(s) out of date; run node ${script}`)
      process.exitCode = 1
    } else if (drift === 0) console.log(`cli reference: up to date`)
  }
}

main()

/**
 * Projects the product docs (apps/site/docs/app) onto smithers.sh/docs from
 * their one source: a Starlight page per toc.ts page, a Markdown copy of each
 * at /docs/<slug>.md, and the sidebar astro.config.mjs reads. `welcome`
 * publishes at /docs/. Check mode compares bytes so the projection cannot
 * diverge from its source.
 *
 * Screenshots are not copied here: scripts/app-docs-integration.mjs serves
 * apps/site/docs/app/images at /images/docs/ in `astro dev` and copies it into
 * the build.
 *
 * Usage: node apps/site/scripts/sync-app-docs.mjs [--check]
 *
 * @since 1.0.0
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join, relative, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { mapInlineProse, splitMarkdownCodeBlocks } from "./docs-text.mjs"

const site = resolve(import.meta.dirname, "..")
const root = resolve(site, "../..")
const source = "apps/site/docs/app"
const origin = "https://smithers.sh"

/** The docs' screenshot directory, served at /images/docs/. */
export const appDocsImages = join(root, source, "images")

/** The comment every projected page opens its frontmatter with. */
export const MARKER = "# GENERATED by apps/site/scripts/sync-app-docs.mjs."

/** The width and height a screenshot renders at: 1440x900 CSS pixels, captured at 2x. */
const SHOT = { width: 1440, height: 900 }

const SLUG = "[a-z0-9]+(?:-[a-z0-9]+)*"
const SLUG_ONLY = new RegExp(`^${SLUG}$`)
const PAGE_LINK = new RegExp(`^(?:\\./)?(${SLUG})\\.md(#[^\\s)]*)?$`)
const BLOCK_IMAGE = new RegExp(`^([ \\t]*)!\\[((?:[^\\]\\\\]|\\\\.)+)\\]\\(images/(${SLUG})\\.webp\\)[ \\t]*$`)

/**
 * Pages the site publishes beside the app's: Install joins the self-host
 * section (a group of its own when toc.ts drops that label), and the
 * reference closes the sidebar. The CLI page is gen-cli-reference.mjs's.
 */
const SITE_ITEMS = [{ label: "On your own Mac", items: [{ slug: "docs/installation" }] }]
const REFERENCE = {
  label: "Reference",
  items: [
    { label: "HTTP and RPC API", slug: "docs/reference/http-api" },
    { label: "CLI", slug: "docs/reference/cli" },
    { label: "Library API", slug: "docs/reference/api" }
  ]
}

/** A page's published path under /docs: `welcome` is the index. */
export const route = (slug) => (slug === "welcome" ? "/docs/" : `/docs/${slug}/`)
/** Where a page's Markdown copy publishes. */
export const copyRoute = (slug) => (slug === "welcome" ? "/docs/index.md" : `/docs/${slug}.md`)
/** A page's Starlight slug. */
const starlightSlug = (slug) => (slug === "welcome" ? "docs" : `docs/${slug}`)

/**
 * The sections toc.ts declares. The file is a literal list of
 * `{ label: "...", pages: ["...", ...] }`, read as text so no TypeScript
 * runs; anything else in the list throws rather than being skipped.
 */
export function parseToc(text) {
  const start = text.indexOf("export const TOC")
  const open = start === -1 ? -1 : text.indexOf("[", text.indexOf("=", start))
  let close = -1
  for (let at = open, depth = 0, quoted = false; open !== -1 && at < text.length; at++) {
    const char = text[at]
    if (quoted) {
      if (char === "\\") at++
      else if (char === "\"") quoted = false
    } else if (char === "\"") quoted = true
    else if (char === "[") depth++
    else if (char === "]" && --depth === 0) {
      close = at
      break
    }
  }
  if (close === -1) throw new Error(`${source}/toc.ts: no \`export const TOC = [...]\` list`)
  const list = text.slice(open + 1, close).replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, "")
  const entry = /\{\s*label:\s*("(?:[^"\\]|\\.)*")\s*,\s*pages:\s*\[([^\]]*)\]\s*,?\s*\}/g
  const sections = [...list.matchAll(entry)].map(([, label, pages]) => {
    const slugs = [...pages.matchAll(/"([^"]*)"/g)].map((match) => match[1])
    if (pages.replace(/"[^"]*"/g, "").replace(/[\s,]/g, "") !== "" || slugs.some((slug) => !SLUG_ONLY.test(slug))) {
      throw new Error(`${source}/toc.ts: section ${label} lists something other than page slugs`)
    }
    return { label: JSON.parse(label), pages: slugs }
  })
  if (sections.length === 0 || list.replace(entry, "").replace(/[\s,]/g, "") !== "") {
    throw new Error(`${source}/toc.ts: TOC must be a literal list of { label, pages } sections`)
  }
  return sections
}

/** A page file's title, summary and body: `title` and `summary` frontmatter, then Markdown. */
export function parsePage(text, name) {
  const lines = text.replace(/\r\n/g, "\n").split("\n")
  const close = lines[0] === "---" ? lines.indexOf("---", 1) : -1
  if (close === -1) throw new Error(`${name}: no --- frontmatter block`)
  const values = {}
  for (const line of lines.slice(1, close)) {
    const match = /^(title|summary):(.*)$/.exec(line)
    if (!match) throw new Error(`${name}: frontmatter line ${JSON.stringify(line)} is not title or summary`)
    const value = match[2].trim()
    values[match[1]] = /^".*"$/.test(value) ? JSON.parse(value) : value
  }
  if (!values.title || !values.summary) throw new Error(`${name}: frontmatter needs a title and a summary`)
  return { title: values.title, summary: values.summary, markdown: lines.slice(close + 1).join("\n").replace(/^(?:[ \t]*\n)+/, "") }
}

const attribute = (value) => value.replaceAll("&", "&amp;").replaceAll("\"", "&quot;").replaceAll("<", "&lt;").replaceAll(">", "&gt;")
const unescape = (text) => text.replace(/\\([!-/:-@[-`{-~])/g, "$1")

/**
 * Rewrites a page body for one destination. A block image on its own line
 * becomes `image(alt, id, indent)` with its Markdown alt escapes;
 * a sibling page link (`flows.md#anchor`)
 * becomes `page(slug, hash)`. Fragments, web links and code stay as written,
 * and any other relative link is left for check-docs to reject.
 */
export function rewrite(markdown, { image, page }) {
  const parts = splitMarkdownCodeBlocks(markdown)
  return parts.map((part, index) => {
    if (index % 2 === 1) return part
    // An HTML block runs to the next blank line, so each image gets one on
    // both sides. A part's last element is the start of the line a fence
    // opens on, not a blank line.
    const blank = (line, last) => line.trim() === "" && !(last && index < parts.length - 1)
    const source = part.split("\n")
    const lines = []
    source.forEach((line, at) => {
      const shot = BLOCK_IMAGE.exec(line)
      if (!shot) return void lines.push(line)
      if (lines.length > 0 && lines.at(-1).trim() !== "") lines.push("")
      lines.push(...image(shot[2], shot[3], shot[1]).split("\n"))
      if (at + 1 < source.length && !blank(source[at + 1], at + 2 === source.length)) lines.push("")
    })
    return mapInlineProse(lines.join("\n"), (prose) =>
      prose.replace(/(!?)\[([^\]]*)\]\(([^)\s]+)\)/g, (link, bang, label, target) => {
        const sibling = bang ? undefined : PAGE_LINK.exec(target)
        return sibling ? `[${label}](${page(sibling[1], sibling[2] ?? "")})` : link
      }))
  }).join("")
}

/** The body Starlight renders: site-absolute links and a framed light/dark screenshot pair. */
export const siteBody = (markdown) =>
  rewrite(markdown, {
    page: (slug, hash) => route(slug) + hash,
    image: (alt, id, indent) => [
      `<figure class="docs-shot">`,
      ...[["light", "dark"], ["dark", "light"]].map(([variant, hidden]) =>
        `<img src="/images/docs/${id}.${variant}.webp" alt="${attribute(unescape(alt))}" width="${SHOT.width}" height="${SHOT.height}" loading="lazy" decoding="async" class="${hidden}:sl-hidden" />`),
      `</figure>`
    ].map((line) => indent + line).join("\n")
  })

/** The Markdown copy: absolute smithers.sh links and the light screenshot. */
export const copyBody = (markdown) =>
  rewrite(markdown, {
    page: (slug, hash) => origin + route(slug) + hash,
    image: (alt, id, indent) => `${indent}![${alt}](${origin}/images/docs/${id}.light.webp)`
  })

const trailing = (text) => text.trimEnd() + "\n"

/** The Starlight page for one app page. */
export const sitePage = (slug, { title, summary, markdown }) => trailing([
  "---",
  `${MARKER} Edit ${source}/pages/${slug}.md.`,
  `editUrl: https://github.com/smithersai/smithers/edit/main/${source}/pages/${slug}.md`,
  `title: ${JSON.stringify(title)}`,
  `description: ${JSON.stringify(summary)}`,
  "head:",
  "  - tag: link",
  "    attrs:",
  "      rel: alternate",
  "      type: text/markdown",
  `      href: ${copyRoute(slug)}`,
  "---",
  "",
  siteBody(markdown)
].join("\n"))

/** The Markdown copy for one app page. */
export const markdownCopy = ({ title, summary, markdown }) => trailing(`# ${title}\n\n> ${summary}\n\n${copyBody(markdown)}`)

/** The Starlight sidebar: one group per toc.ts section, the site's own pages, then the reference. */
export function sidebar(sections) {
  const groups = sections
    .map(({ label, pages }) => ({ label, items: pages.map((slug) => ({ slug: starlightSlug(slug) })) }))
  for (const extra of SITE_ITEMS) {
    const group = groups.find(({ label }) => label === extra.label)
    if (group) group.items.push(...extra.items)
    else groups.push(structuredClone(extra))
  }
  return [...groups.filter(({ items }) => items.length > 0), REFERENCE]
}

/** Every file the projection owns, by repository path, with its content. */
export function projection() {
  const sections = parseToc(readFileSync(join(root, source, "toc.ts"), "utf8"))
  const files = new Map()
  const published = []
  for (const section of sections) {
    const pages = []
    for (const slug of section.pages) {
      const path = join(root, source, "pages", `${slug}.md`)
      // A listed page with no file is an error, never a silently shorter sidebar.
      if (!existsSync(path)) throw new Error(`app docs: toc.ts lists ${slug}, but ${source}/pages/${slug}.md does not exist`)
      const page = parsePage(readFileSync(path, "utf8"), `${source}/pages/${slug}.md`)
      const file = slug === "welcome" ? "index" : slug
      files.set(`apps/site/src/content/docs/docs/${file}.md`, sitePage(slug, page))
      files.set(`apps/site/public${copyRoute(slug)}`, markdownCopy(page))
      pages.push(slug)
    }
    published.push({ label: section.label, pages })
  }
  files.set("apps/site/src/data/docs-sidebar.json", JSON.stringify(sidebar(published), null, 2) + "\n")
  return files
}

/**
 * Earlier projections this run no longer produces: marked pages in the docs
 * tree and every file directly under public/docs. Its subdirectories hold
 * other projections' copies (reference/, gen-cli-reference.mjs).
 */
function stale(files) {
  const owned = []
  const docs = join(site, "src/content/docs/docs")
  for (const name of existsSync(docs) ? readdirSync(docs).filter((name) => name.endsWith(".md")) : []) {
    if (readFileSync(join(docs, name), "utf8").includes(MARKER)) owned.push(join(docs, name))
  }
  const copies = join(site, "public/docs")
  if (existsSync(copies)) {
    owned.push(...readdirSync(copies, { withFileTypes: true }).filter((entry) => entry.isFile()).map(({ name }) => join(copies, name)))
  }
  return owned.map((path) => relative(root, path)).filter((path) => !files.has(path))
}

// Run as a script, not imported. realpath: a module URL names the resolved file.
if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check")
  const files = projection()
  let drift = 0
  for (const [path, content] of files) {
    const target = join(root, path)
    if (check) {
      if (!existsSync(target) || readFileSync(target, "utf8") !== content) {
        console.error(`app docs drift: ${path}`)
        drift++
      }
    } else {
      mkdirSync(dirname(target), { recursive: true })
      writeFileSync(target, content)
    }
  }
  for (const path of stale(files)) {
    if (check) {
      console.error(`app docs drift: ${path} is no longer in ${source}/toc.ts`)
      drift++
    } else rmSync(join(root, path))
  }
  if (drift > 0) {
    console.error(`app docs: ${drift} file(s) out of date; run node apps/site/scripts/sync-app-docs.mjs`)
    process.exitCode = 1
  } else console.log(`app docs: ${files.size} files ${check ? "checked" : "written"}`)
}

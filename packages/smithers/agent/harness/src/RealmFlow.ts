/**
 * Fresh, bounded execution of pinned Flow.make modules. Action requests, agent
 * steps included, cross the realm as data; the caller journals their outcomes.
 * @since 1.0.0-rc.16
 */

import { BoundedJson } from "@smthrs/canonical"
import { digestSync } from "@smthrs/crypto"
import { Clock, Effect, Schema } from "effect"
import { getVersion, transform } from "sucrase"
import { source as bundle } from "./internal/RealmFlowBundle.ts"
import * as QuickJSLifecycle from "./QuickJSLifecycle.ts"
import { layerVariantLive } from "./QuickJSSandbox.ts"
import * as QuickJSVariant from "./QuickJSVariant.ts"

/**
 * A host-dispatched action addressed by its canonical interpreter node.
 *
 * @category models
 * @since 1.0.0-rc.16
 */
export interface Request {
  readonly _tag: "Action"
  readonly key: string
  readonly name: string
  readonly payload: unknown
}
/**
 * The immutable outcome of a previously dispatched request.
 *
 * @category models
 * @since 1.0.0-rc.16
 */
export interface Receipt extends Request {
  readonly outcome: { readonly _tag: "Success"; readonly value: unknown } | {
    readonly _tag: "Failure"
    readonly error: unknown
  }
}
/**
 * Pinned code and durable progress supplied by the host.
 *
 * @category models
 * @since 1.0.0-rc.16
 */
export interface Input {
  readonly source: string
  readonly expectedTag: string
  readonly payload: unknown
  readonly allowedActions: ReadonlyArray<string>
  readonly receipts?: ReadonlyArray<Receipt>
}
/**
 * One action to journal, or the flow's schema-validated result.
 *
 * @category models
 * @since 1.0.0-rc.16
 */
export type Result = Request | { readonly _tag: "Complete"; readonly value: unknown }
/**
 * The host action every agent step is requested as. A host lists it in
 * `allowedActions` to offer agent steps; the request's payload is
 * {@link AgentPayload}, and its receipt's success value is the agent's answer,
 * which the step's declared `output` schema decodes.
 *
 * @category constants
 * @since 1.0.0-rc.17
 */
export const agentAction = "@smthrs/agent/AgentAction"

/**
 * What an agent step asks the host: the step's tag, its declared seat, and the
 * prompt its own `prompt` function rendered inside the realm from the step's
 * decoded payload. The host owns everything else: the model, system teaching,
 * catalog and limits.
 *
 * @category models
 * @since 1.0.0-rc.17
 */
export const AgentPayload = Schema.Struct({ step: Schema.String, seat: Schema.String, prompt: Schema.String })

/**
 * Sanitized refusal; repository source and values never enter diagnostics.
 * `forbidden_import` is a module the realm doesn't provide; `action_not_allowed`
 * is an action, or an agent step, the host didn't list in `allowedActions`. The
 * realm refuses with either even when the module catches what it threw.
 *
 * @category models
 * @since 1.0.0-rc.16
 */
export class RealmFlowError extends Schema.TaggedError<RealmFlowError>()("RealmFlowError", {
  code: Schema.Literals([
    "invalid_source",
    "execution_failed",
    "limit_exceeded",
    "runtime_failed",
    "forbidden_import",
    "action_not_allowed"
  ])
}) {}

/** The closed codes the realm's trusted code records with `__refuse`. */
type Refusal = "forbidden_import" | "action_not_allowed"

const prelude = `
class TextEncoder { encode(text) { return Uint8Array.from(unescape(encodeURIComponent(text)), c => c.charCodeAt(0)); } }
class TextDecoder { decode(bytes = []) { return decodeURIComponent(escape(Array.from(bytes, n => String.fromCharCode(n)).join(""))); } }
let __modules, __run, __refusal;
function __publish(modules, run) { __modules = modules; __run = run; }
function __refuse(code) { if (__refusal === undefined) __refusal = code; }
`
const harden = `
${QuickJSLifecycle.prelude(["WeakRef", "FinalizationRegistry", "setTimeout", "setInterval"])}
// Authoring and interpretation share this realm. Neither its intrinsics nor
// the public SDK objects may be rewritten by repository code.
const __frozen = new WeakSet();
function __freeze(value) {
  if (value === null || (typeof value !== 'object' && typeof value !== 'function') || __frozen.has(value)) return;
  __frozen.add(value);
  for (const descriptor of Object.values(Object.getOwnPropertyDescriptors(value))) {
    if ('value' in descriptor) __freeze(descriptor.value);
    else { __freeze(descriptor.get); __freeze(descriptor.set); }
  }
  __freeze(Object.getPrototypeOf(value));
  Object.freeze(value);
}
for (const namespace of Object.values(__modules)) {
  // SDK namespace exports are trusted getters generated by the bundler.
  for (const value of Object.values(namespace)) __freeze(value);
  __freeze(namespace);
}
for (const [name, descriptor] of Object.entries(Object.getOwnPropertyDescriptors(globalThis))) {
  if (name === 'globalThis') continue;
  if ('value' in descriptor) {
    __freeze(descriptor.value);
    Object.defineProperty(globalThis, name, { ...descriptor, writable: false, configurable: false });
  }
}
function require(name) { if (!Object.prototype.hasOwnProperty.call(__modules, name)) { __refuse('forbidden_import'); throw Error('forbidden_import'); } return __modules[name]; }
`

/**
 * Content identity of the committed SDK bundle and realm policy. Persist this
 * beside the pinned source; refuse recovery under a different host version.
 *
 * @category identity
 * @since 1.0.0-rc.16
 */
export const version = digestSync(JSON.stringify({
  bundle,
  prelude,
  harden,
  compiler: getVersion(),
  transport: 1,
  limits: {
    memoryBytes: 64 * 1024 * 1024,
    stackBytes: QuickJSLifecycle.stackBytes,
    milliseconds: 1000,
    interrupts: 2000,
    bytes: 256 * 1024
  }
}))

/**
 * Evaluates the actual SDK interpreter in a fresh QuickJS realm. Supply the
 * existing QuickJSVariant layer for the host; the host executes and journals
 * returned action requests before calling step again with their receipts.
 *
 * @category execution
 * @since 1.0.0-rc.16
 */
export const step = (input: Input): Effect.Effect<Result, RealmFlowError, QuickJSVariant.Variant> =>
  Effect.gen(function*() {
    const module = yield* QuickJSVariant.compiledModule.pipe(
      Effect.mapError(() => new RealmFlowError({ code: "runtime_failed" }))
    )
    const clock = yield* Clock.Clock
    return yield* Effect.try({
      try: () => {
        if (BoundedJson.encodedStringBytes(input.source, 256 * 1024) === undefined) {
          throw new RealmFlowError({ code: "limit_exceeded" })
        }
        const compiled = transform(input.source, { transforms: ["typescript", "imports"], filePath: "flow.ts" }).code
        const runtime = module.newRuntime()
        runtime.setMemoryLimit(64 * 1024 * 1024)
        runtime.setMaxStackSize(QuickJSLifecycle.stackBytes)
        const budget = QuickJSLifecycle.interruptBudget(() => clock.currentTimeMillisUnsafe())
        budget.arm(1000, 2000)
        let limited = false
        runtime.setInterruptHandler(() => {
          limited = budget.poll() !== undefined
          return limited
        })
        const context = runtime.newContext()
        try {
          const evaluate = (code: string): string => {
            const evaluated = context.evalCode(code)
            if (evaluated.error !== undefined) {
              evaluated.error.dispose()
              throw new RealmFlowError({ code: limited ? "limit_exceeded" : "execution_failed" })
            }
            const result = context.getString(evaluated.value)
            evaluated.value.dispose()
            return result
          }
          const lastResult = evaluate(
            `(function() { ${prelude}\n${bundle}\n${harden}\nlet result;
try { const exports = {}; (0, eval)(${
              JSON.stringify("(function(exports, require) {" + compiled + "\n})")
            })(exports, require);
result = __run(exports.default, ${JSON.stringify({ ...input, receipts: input.receipts ?? [] })}); }
catch (error) { if (__refusal === undefined) throw error; }
if (__refusal !== undefined) return JSON.stringify({ _tag: 'Refused', code: __refusal });
const output = JSON.stringify(result); if (new TextEncoder().encode(output).byteLength > 262144) throw Error('output_limit'); return output; })()`
          )
          // Evaluate once: getString above crosses only the bounded JSON output.
          // Only the realm's trusted code records a refusal, and only with its closed codes.
          const parsed = JSON.parse(lastResult) as Result | { readonly _tag: "Refused"; readonly code: Refusal }
          if (parsed._tag === "Refused") throw new RealmFlowError({ code: parsed.code })
          return parsed
        } finally {
          context.dispose()
          runtime.dispose()
        }
      },
      catch: (error) => error instanceof RealmFlowError ? error : new RealmFlowError({ code: "invalid_source" })
    })
  })

/**
 * Default single-file QuickJS build for Node and browsers. Workers supply their compiled variant.
 *
 * @category models
 * @since 1.0.0-rc.16
 */
export const layerDefaultVariant = layerVariantLive

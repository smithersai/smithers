/**
 * Regenerates `src/internal/AtomicFileSystemHelperSource.ts` from
 * `src/internal/AtomicFileSystemHelper.py`.
 *
 * The Python file is the one source of the POSIX helper. The adapter runs it
 * as `python3 -c <source>` and the package publishes TypeScript only, so the
 * source ships embedded in a generated module. The template opens with a
 * newline, so the embedded program is that newline followed by the file, byte
 * for byte.
 *
 * Usage: node scripts/generate-atomic-helper.mjs [--check]
 *
 * `--check` writes nothing and exits 1 when the committed module differs from
 * what this script would write.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const internal = join(dirname(fileURLToPath(import.meta.url)), "../src/internal")
const pythonFile = join(internal, "AtomicFileSystemHelper.py")
const moduleFile = join(internal, "AtomicFileSystemHelperSource.ts")

const python = readFileSync(pythonFile, "utf8")
// `String.raw` keeps every backslash, but a backtick ends the template, `${`
// interpolates, and the parser turns a carriage return into a line feed: each
// would change the program that runs.
for (const [token, name] of [["`", "a backtick"], ["${", "`${`"], ["\r", "a carriage return"]]) {
  if (python.includes(token)) {
    console.error(`${pythonFile} contains ${name}, which String.raw cannot embed unchanged`)
    process.exit(1)
  }
}

const generated = `/**
 * The POSIX helper program the atomic filesystem adapter runs.
 *
 * Generated by \`scripts/generate-atomic-helper.mjs\` from
 * \`AtomicFileSystemHelper.py\` beside this file. Do not edit by hand: edit the
 * Python file and rerun the script. The template opens with a newline, so the
 * program is that newline followed by the file, byte for byte.
 * @private
 * @since 1.0.0
 */
export const source = String.raw\`
${python}\`
`

if (process.argv.includes("--check")) {
  if (readFileSync(moduleFile, "utf8") !== generated) {
    console.error(`${moduleFile} is stale: run node scripts/generate-atomic-helper.mjs`)
    process.exit(1)
  }
} else {
  writeFileSync(moduleFile, generated)
}

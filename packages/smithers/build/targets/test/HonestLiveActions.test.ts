import { Flow, FlowRuntime } from "@smthrs/flow"
import * as Effect from "effect/Effect"
import * as Latch from "effect/Latch"
import * as Layer from "effect/Layer"
import * as Fs from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { afterEach, beforeEach, expect, it } from "vitest"
import * as Compose from "../src/Compose.ts"
import * as DocsParity from "../src/DocsParity.ts"
import * as Exec from "../src/Exec.ts"
import * as GeneratedFile from "../src/GeneratedFile.ts"
import * as Review from "../src/LlmLint.ts"
import * as NewPackage from "../src/NewPackage.ts"
import * as PackageJson from "../src/PackageJson.ts"
import * as ToolBuild from "../src/ToolBuild.ts"

let root: string
beforeEach(async () => {
  root = await Fs.realpath(await Fs.mkdtemp(join(tmpdir(), "honest-live-actions-")))
})
afterEach(async () => {
  await Fs.rm(root, { recursive: true, force: true })
})

// A minimal FlowRuntime executes each registered action using the real layer.
// No action result is replaced: file publication, checking and subprocesses run.
const execute = <A>(layer: Layer.Layer<A, never, FlowRuntime.FlowRuntime>, payload: unknown) => {
  let registered: ((payload: unknown, id: string) => Effect.Effect<unknown, unknown>) | undefined
  const runtime = FlowRuntime.FlowRuntime.of(
    {
      register: (_flow: unknown, action: typeof registered) =>
        Effect.sync(() => {
          registered = action
        }),
      actionExecute: (action: { execute: Effect.Effect<unknown, unknown> }) =>
        Effect.map(Effect.exit(action.execute), (exit) => new Flow.Complete({ exit }))
    } as unknown as FlowRuntime.FlowRuntime["Service"]
  )
  return Effect.runPromise(Effect.scoped(Effect.gen(function*() {
    yield* Layer.build(layer.pipe(Layer.provide(Layer.succeed(FlowRuntime.FlowRuntime, runtime))))
    if (registered === undefined) throw new Error("action not registered")
    return yield* registered(payload, "honest-live-actions").pipe(
      Effect.provideService(FlowRuntime.FlowRuntime, runtime),
      Effect.provideService(
        FlowRuntime.FlowInstance,
        FlowRuntime.FlowInstance.of({
          executionId: "honest-live-actions",
          actionState: { count: 0, latch: Latch.makeUnsafe() }
        } as never)
      )
    )
  })))
}

it("publishes and verifies generated bytes through their registered actions", async () => {
  const payload = { path: "nested/value.txt", contents: "value\n" }
  await execute(GeneratedFile.WriteFileLive({ workspaceRoot: root }), payload)
  expect(await Fs.readFile(join(root, payload.path), "utf8")).toBe(payload.contents)
  await expect(execute(GeneratedFile.CheckFileLive({ workspaceRoot: root }), payload)).resolves.toBeUndefined()
  await expect(execute(GeneratedFile.CheckFileLive({ workspaceRoot: root }), { ...payload, contents: "wrong\n" }))
    .rejects.toThrow(/drift|differs|line/)
  expect(await Fs.readFile(join(root, payload.path), "utf8")).toBe(payload.contents)
})

it("scaffolds a real package and refuses to overwrite it", async () => {
  const layer = NewPackage.ScaffoldPackageLive({ workspaceRoot: root, packageName: "@example/created" })
  const payload = { directory: "packages", version: "0.1.0", license: "MIT", fields: {} }
  const report = await execute(layer, payload)
  expect(report).toMatchObject({ directory: "packages/created" })
  expect(JSON.parse(await Fs.readFile(join(root, "packages/created/package.json"), "utf8"))).toMatchObject({
    name: "@example/created",
    version: "0.1.0"
  })
  await expect(execute(layer, payload)).rejects.toThrow(/exist/)
})

it("writes manifest metadata through its registered synchronizer", async () => {
  await execute(PackageJson.SyncPackageJsonLive({ workspaceRoot: root, cacheDirectory: ".cache" }), {
    path: "package.json",
    mode: "write",
    fields: { name: "example", version: "1.0.0" },
    generated: [],
    readme: null,
    sources: null,
    promptVersion: "1",
    engine: "claude",
    model: "sonnet"
  })
  expect(JSON.parse(await Fs.readFile(join(root, "package.json"), "utf8"))).toEqual({
    name: "example",
    version: "1.0.0"
  })
})

it("captures output digests and rejects absent outputs through its live action", async () => {
  await Fs.writeFile(join(root, "value"), "value")
  const layer = ToolBuild.CaptureOutputsLive({ workspaceRoot: root })
  const report = await execute(layer, { cwd: ".", paths: ["value"] })
  expect(report).toMatchObject({ outputs: [{ path: "value" }] })
  await expect(execute(layer, { cwd: ".", paths: ["missing"] })).rejects.toThrow(/not created/)
})

it("executes a command through the registered exec boundary", async () => {
  const result = await execute(Exec.ExecLive({ workspaceRoot: root }), {
    cwd: ".",
    argv: [process.execPath, "-e", "process.stdout.write('completed')"],
    env: {},
    secrets: [],
    expectedExitCodes: [0],
    timeoutMs: 10000
  })
  expect(result).toMatchObject({ exitCode: 0, stdout: "completed" })
})

it("runs a README check through the registered live layer", async () => {
  await Fs.writeFile(join(root, "README.md"), "# Widget\n\nThe widget reads a file and returns its contents.\n")
  await expect(
    execute(DocsParity.CheckDocsLive({ workspaceRoot: root }), { path: "README.md", minimumProseCharacters: 10 })
  ).resolves.toBeUndefined()
})

it("checks a generator through its registered action", async () => {
  await Fs.writeFile(join(root, "value"), "original")
  await expect(execute(Compose.GenerateCheckLive({ workspaceRoot: root }), {
    run: {
      cwd: ".",
      argv: [process.execPath, "-e", "void 0"],
      env: {},
      secrets: [],
      expectedExitCodes: [0],
      timeoutMs: 10000
    },
    changes: ["value"]
  })).resolves.toBeUndefined()
  expect(await Fs.readFile(join(root, "value"), "utf8")).toBe("original")
})

it("does not launch inference for an empty optional review action", async () => {
  await expect(execute(Review.LlmReviewLive({ workspaceRoot: root, snapshot: [] }), {
    base: "HEAD",
    include: [],
    context: [],
    prompt: "Review",
    rubric: "Defects",
    engine: "claude",
    model: "test",
    batchSize: 1,
    failOn: "error",
    scope: "all"
  })).resolves.toMatchObject({ files: [], findings: [] })
})

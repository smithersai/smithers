// Writes InventorySpec/CaseTables.lean: the one-character case mappings of ECMAScript's `toUpperCase` and
// `toLowerCase`, as this Node's Unicode data has them. Run: node scripts/gen-case-tables.mjs > InventorySpec/CaseTables.lean
const pairs = (map) => {
  const found = []
  for (let cp = 0x80; cp <= 0x10ffff; cp += 1) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue
    const from = String.fromCodePoint(cp)
    const to = map(from)
    // `fold` keeps a character whose upper case has another length; `lower` handles U+0130 by hand.
    if (to !== from && to.length === from.length && [...to].length === 1) found.push([cp, to.codePointAt(0)])
  }
  return found
}
/** Runs of code points a fixed stride apart that all move by the same distance: [first, last, stride, first's image]. */
const ranges = (found) => {
  const out = []
  let i = 0
  while (i < found.length) {
    const [lo, to] = found[i]
    let stride = 1
    let j = i
    for (const s of [1, 2]) {
      let k = i
      while (k + 1 < found.length && found[k + 1][0] === found[k][0] + s && found[k + 1][1] === found[k][1] + s) k += 1
      if (k > j) {
        j = k
        stride = s
      }
    }
    out.push([lo, found[j][0], stride, to])
    i = j + 1
  }
  return out
}
const table = (name, doc, found) =>
  `/-- ${doc} -/\ndef ${name} : Array (Nat × Nat × Nat × Nat) := #[\n` +
  ranges(found).map(([a, b, s, t]) => `  (${a}, ${b}, ${s}, ${t})`).join(",\n") + "\n]\n"
const upper = pairs((c) => c.toUpperCase())
const lower = pairs((c) => c.toLowerCase())
process.stdout.write(
  `/-\nGenerated by scripts/gen-case-tables.mjs from Node ${process.version} (Unicode ${process.versions.unicode}). Do not edit.\n` +
  `Each row is (first, last, stride, image of first): a code point c with first ≤ c ≤ last and\n(c - first) % stride = 0 maps to image + (c - first). Code points below U+0080 are handled in Unicode.lean.\n-/\n` +
  `namespace InventorySpec\n\n` +
  table("upperRanges", "`toUpperCase` of one character, where the result is one character of the same UTF-16 length.", upper) + "\n" +
  table("lowerRanges", "`toLowerCase` of one character standing alone, where the result is one character.", lower) +
  `\nend InventorySpec\n`
)

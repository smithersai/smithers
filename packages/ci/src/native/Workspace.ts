/**
 * A repository that already builds with Smithers build: how the inventory
 * says so, and how the program words its refusal to convert it.
 *
 * @since 0.1.0
 */

import { type Inventory, ownWorkspace, smithersBuild, type Unsupported } from "../contract/Inventory.ts"
import type { GeneratedFile } from "../contract/Parts.ts"

/**
 * How every Smithers build file `smithers-ci` generates starts.
 *
 * @category constants
 * @since 0.1.0
 */
export const generatedMark = "// Generated by smithers-ci."

/**
 * Whether `smithers-ci` wrote a file with this text. Only such a file is
 * ever written over.
 *
 * @throws {never}
 * @category accessors
 * @since 0.1.0
 */
export const isGenerated = (text: string): boolean => text.startsWith(generatedMark)

/**
 * The inventory entry for a repository whose own workspace is `file`.
 *
 * @throws {never}
 * @category constructors
 * @since 0.1.0
 */
export const found = (file: string): Unsupported => ({ feature: smithersBuild, detail: file })

/**
 * Why nothing is generated for this repository, or `undefined` when it has
 * no workspace of its own. Its CI is already its targets.
 *
 * @throws {never}
 * @category accessors
 * @since 0.1.0
 */
export const refusal = (inventory: Inventory): string | undefined => {
  const file = ownWorkspace(inventory)
  return file === undefined
    ? undefined
    : `the repository already builds with Smithers build (${file}); there is nothing to convert`
}

/**
 * Whether a generated file is a Smithers build file: a workspace or a
 * package, in any directory.
 *
 * @throws {never}
 * @category accessors
 * @since 0.1.0
 */
export const isBuildFile = (file: GeneratedFile): boolean => /(^|\/)(WORKSPACE|PACKAGE)\.(ts|vibe)$/.test(file.path)

/**
 * Why generated files cannot be written: `paths` are build files the
 * repository's owner wrote.
 *
 * @throws {never}
 * @category accessors
 * @since 0.1.0
 */
export const overwriteRefusal = (paths: ReadonlyArray<string>): string =>
  `${paths.join(", ")} ${paths.length === 1 ? "was" : "were"} not written by smithers-ci and would be replaced`

/**
 * What the text report ends with after a replay of the repository's own
 * targets.
 *
 * @throws {never}
 * @category accessors
 * @since 0.1.0
 */
export const footer = (file: string): string =>
  `This repository already builds with Smithers build (${file}). The replay ran its own targets, cold against cached; there is nothing for apply to convert. This run wrote nothing to the repository.`

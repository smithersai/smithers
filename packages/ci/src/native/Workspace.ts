/**
 * A repository that already builds with Smithers build: how the inventory
 * says so, and how the program words its refusal to convert it. Also how a
 * file `smithers-ci` generated is told from one an owner wrote.
 *
 * @since 0.1.0
 */

import * as Option from "effect/Option"
import * as Schema from "effect/Schema"
import { type Inventory, ownWorkspace, smithersBuild, type Unsupported } from "../contract/Inventory.ts"
import type { GeneratedFile } from "../contract/Parts.ts"
import { path as targetMapPath, TargetMap } from "../contract/TargetMap.ts"

const said = "Generated by smithers-ci."

/**
 * How every Smithers build file `smithers-ci` generates starts.
 *
 * @category constants
 * @since 0.1.0
 */
export const generatedMark = `// ${said}`

/** The mark as each kind of generated file writes it on its first line: TypeScript, then YAML. */
const marks = [generatedMark, `# ${said}`]

/** A Markdown file carries the mark as the first line under its heading. */
const underHeading = /^# [^\n]*\n\nGenerated by smithers-ci\./

/**
 * Whether a file with this text starts with the generated mark, as a
 * TypeScript or a YAML comment.
 *
 * @throws {never}
 * @category accessors
 * @since 0.1.0
 */
export const isGenerated = (text: string): boolean => marks.some((mark) => text.startsWith(mark))

const targetMapOf = Schema.decodeUnknownOption(Schema.fromJsonString(TargetMap))

/**
 * Whether `smithers-ci` wrote the file at `path` whose text is `text`. Only
 * such a file is ever written over. It starts with the generated mark, or
 * is Markdown with the mark under its heading. The target map is JSON, which
 * has no comment to hold a mark: the file at the target map's path counts
 * when it is a target map.
 *
 * @throws {never}
 * @category accessors
 * @since 0.1.0
 */
export const wrote = (path: string, text: string): boolean =>
  isGenerated(text) || underHeading.test(text) || (path === targetMapPath && Option.isSome(targetMapOf(text)))

/**
 * The inventory entry for a repository whose own workspace is `file`.
 *
 * @throws {never}
 * @category constructors
 * @since 0.1.0
 */
export const found = (file: string): Unsupported => ({ feature: smithersBuild, detail: file })

/**
 * Why nothing is generated for this repository, or `undefined` when it has
 * no workspace of its own. Its CI is already its targets.
 *
 * @throws {never}
 * @category accessors
 * @since 0.1.0
 */
export const refusal = (inventory: Inventory): string | undefined => {
  const file = ownWorkspace(inventory)
  return file === undefined
    ? undefined
    : `the repository already builds with Smithers build (${file}); there is nothing to convert`
}

/**
 * Whether a generated file is a Smithers build file: a workspace or a
 * package, in any directory.
 *
 * @throws {never}
 * @category accessors
 * @since 0.1.0
 */
export const isBuildFile = (file: GeneratedFile): boolean => /(^|\/)(WORKSPACE|PACKAGE)\.(ts|vibe)$/.test(file.path)

/**
 * Why generated files cannot be written: `paths` are files the repository's
 * owner wrote.
 *
 * @throws {never}
 * @category accessors
 * @since 0.1.0
 */
export const overwriteRefusal = (paths: ReadonlyArray<string>): string =>
  `${paths.join(", ")} ${paths.length === 1 ? "was" : "were"} not written by smithers-ci and would be replaced`

const wroteNothing = "This run wrote nothing to the repository."

/**
 * What the text report ends with after a replay of the repository's own
 * targets. `file` is the workspace file in the working tree; without one,
 * only the newest commit holds it. `wrote` says what the run wrote to the
 * repository.
 *
 * @throws {never}
 * @category accessors
 * @since 0.1.0
 */
export const footer = (file: string | undefined, wrote: string = wroteNothing): string =>
  `${
    file === undefined
      ? "The newest commit already builds with Smithers build"
      : `This repository already builds with Smithers build (${file})`
  }. The replay ran its own targets, cold against cached; there is nothing for apply to convert. ${wrote}`

/**
 * What the text report ends with when the working tree holds a workspace
 * file, `file`, that the newest commit does not: the replay ran the commit,
 * so it generated targets, and `apply` converts nothing while the file is
 * there.
 *
 * @throws {never}
 * @category accessors
 * @since 0.1.0
 */
export const uncommittedFooter = (file: string, wrote: string = wroteNothing): string =>
  `The replay ran targets generated from the newest commit, which has no Smithers workspace: ${file} is not committed. smithers-ci apply converts nothing while that file is there. ${wrote}`

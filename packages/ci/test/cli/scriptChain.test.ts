/**
 * A CI step that runs a script made of other scripts, end to end, once for
 * each package manager on this machine: npm, pnpm 10, pnpm 11, Yarn 1 and Bun.
 *
 * The repository's `check` is `format && spell && types`. The first two read
 * the docs and the last reads the source. The real program replays three
 * commits with the real package manager, `node` and `smthrs`:
 *
 * - a commit that changes only the docs runs again the two scripts that read
 *   them, and answers the third from its record;
 * - a commit that breaks the docs fails the middle script: the script after
 *   it does not run, and the step's verdict is the one the repository's own
 *   CI gives;
 * - a second step runs the same scripts joined by `;`, which goes on after a
 *   failure. It is never split, and `smithers-ci inventory` says why.
 *
 * What a step reads is recorded by `strace`, so the cases run on a Linux host
 * that has it.
 */
import { spawnSync } from "node:child_process"
import { existsSync, readdirSync } from "node:fs"
import { homedir } from "node:os"
import { join } from "node:path"
import { afterAll, describe, expect, it } from "vitest"
import type { ReplayReport } from "../../src/contract/ReplayReport.ts"
import { bin, commit, git, observes, remove, spawn, temporary } from "./repo.ts"

const made: Array<string> = []
afterAll(() => made.forEach(remove))

interface Manager {
  /** The program. */
  readonly name: string
  /** The program and the releases the case is for. */
  readonly label: string
  /** The words a script runs another script with. */
  readonly run: string
  /** The words the workflow runs a script with. */
  readonly step: string
  /** Files that say which release runs the scripts. */
  readonly files: Readonly<Record<string, string>>
  /**
   * When corepack runs it: the releases the repository may name in `packageManager`, said in words for a machine
   * that keeps none, and which those are.
   */
  readonly corepack?: { readonly wanted: string; readonly accepts: (release: string) => boolean }
  /**
   * Whether a step's result is kept on a machine other programs use. Bun looks at the temporary directory itself
   * each time it starts, and a step whose record holds a path that changed while it ran is not kept
   * (`/tmp changed while it ran`): on a shared machine a Bun step runs again at every commit, split or whole.
   */
  readonly kept: boolean
}


const installed = (name: string): boolean => spawnSync(name, ["--version"], { cwd: "/" }).status === 0

const workflow = (manager: Manager): string =>
  [
    "name: CI",
    "on:",
    "  push:",
    "    branches: [main]",
    "  pull_request:",
    // Yarn 1 keeps compiled code of its own under the temporary directory and rewrites it as it runs, which would
    // make a step that starts Yarn read a file that changed. The repository turns that cache off, as its CI may.
    "env:",
    "  DISABLE_V8_COMPILE_CACHE: \"1\"",
    "jobs:",
    "  check:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    "      - uses: actions/checkout@v4",
    "      - name: Check",
    `        run: ${manager.step} verify`,
    "  loose:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    "      - uses: actions/checkout@v4",
    "      - name: Loose check",
    `        run: ${manager.step} loose`,
    ""
  ].join("\n")

/** Fails when a file under `docs` holds what it looks for, and names the file. */
const docsCheck = (what: string, pattern: string): string =>
  [
    "const fs = require(\"node:fs\")",
    "for (const file of fs.readdirSync(\"docs\")) {",
    `  if (${pattern}.test(fs.readFileSync(\`docs/\${file}\`, "utf8"))) {`,
    `    console.error(\`${what} in docs/\${file}\`)`,
    "    process.exit(1)",
    "  }",
    "}",
    ""
  ].join("\n")

/** The first number of a release, `12` for `12.15.0`. */
const majorOf = (release: string): number => Number(/^\d+/.exec(release)?.[0] ?? Number.NaN)

/** The second number of a release, `15` for `12.15.0`. */
const minorOf = (release: string): number => Number(/^\d+\.(\d+)/.exec(release)?.[1] ?? Number.NaN)

/**
 * The newest release of a corepack-run manager this machine's corepack keeps that `accepts` takes, as
 * `packageManager` names it. A repository that names one replays with no network: a step's corepack finds it in
 * its own home. A machine that keeps none fails the case and says what to install.
 */
const kept = (name: string, corepack: NonNullable<Manager["corepack"]>): string => {
  const caches = process.env["XDG_CACHE_HOME"] ?? join(homedir(), ".cache")
  const versions = join(process.env["COREPACK_HOME"] ?? join(caches, "node", "corepack"), "v1", name)
  const version = existsSync(versions)
    ? readdirSync(versions).filter((entry) => !entry.startsWith(".") && corepack.accepts(entry)).sort(byRelease).at(-1)
    : undefined
  if (version === undefined) {
    throw new Error(
      `corepack keeps no ${corepack.wanted} in ${versions}: run \`corepack ${corepack.wanted} --version\` to keep one`
    )
  }
  return `${name}@${version}`
}

/** Orders releases by their numbers, `9.6.0` before `12.15.0`. */
const byRelease = (left: string, right: string): number => {
  const numbers = (release: string) => (release.match(/^\d+(?:\.\d+)*/)?.[0] ?? "").split(".").map(Number)
  const [a, b] = [numbers(left), numbers(right)]
  for (let at = 0; at < Math.max(a.length, b.length); at++) {
    if ((a[at] ?? 0) !== (b[at] ?? 0)) return (a[at] ?? 0) - (b[at] ?? 0)
  }
  return 0
}

/** The repository at its first commit. */
const repository = (manager: Manager): string => {
  const root = temporary(`chain-${manager.label.replace(/\W+/g, "-")}`)
  made.push(root)
  git(root, "init", "--quiet", "--initial-branch=main")
  commit(root, "base", {
    ".github/workflows/ci.yml": workflow(manager),
    "package.json": JSON.stringify({
      name: "fixture",
      version: "1.0.0",
      private: true,
      ...(manager.corepack === undefined ? {} : { packageManager: kept(manager.name, manager.corepack) }),
      scripts: {
        // `yarn check` is Yarn's own command, so the script has another name.
        verify: `${manager.run} format && ${manager.run} spell && ${manager.run} types`,
        // The same scripts joined by `;`: the last one's verdict is the step's, whatever the others did.
        loose: `${manager.run} format; ${manager.run} spell; ${manager.run} types`,
        format: "node format.js",
        spell: "node spell.js",
        types: "node types.js"
      }
    }),
    ...manager.files,
    "format.js": docsCheck("a tab", "/\\t/"),
    "spell.js": docsCheck("teh", "/\\bteh\\b/"),
    "types.js": "if (require(\"./src/value.js\") !== \"ok\") process.exit(1)\n",
    "src/value.js": "module.exports = \"ok\"\n",
    "docs/readme.md": "# Fixture\n"
  })
  return root
}

describe.each(managers)("a repository whose CI runs a chain of scripts with $label", (manager) => {
  it.skipIf(!observes || !installed(manager.name))(
    "reruns only the scripts that read a changed file, and fails where the chain fails",
    async () => {
      const root = repository(manager)
      commit(root, "docs only", { "docs/readme.md": "# Fixture\n\nMore words.\n" })
      commit(root, "a misspelt word in the docs", { "docs/readme.md": "# Fixture\n\nMore of teh words.\n" })

      const listed = await spawn(bin, ["inventory"], root)
      expect(listed.code, listed.stderr).toBe(0)
      const lines = listed.stdout.split("\n")
      // The chain is listed as the repository wrote it, and the step that cannot be split says why.
      expect(lines[lines.indexOf(`  $ ${manager.step} verify`) + 1]).not.toContain("stays one step")
      expect(lines[lines.indexOf(`  $ ${manager.step} loose`) + 1]).toBe(
        "    stays one step: the script joins commands with `;` or a line break"
      )

      // The newest commit fails on purpose, and its verdict is what is compared: nothing is left out.
      const outcome = await spawn(bin, ["--commits", "3", "--no-apply-check", "--json", "--no-trial"], root)
      expect(outcome.stderr).not.toContain("reads are not observed")
      const report = JSON.parse(outcome.stdout) as ReplayReport
      const subjects = git(root, "log", "--reverse", "--format=%H %s", "-3").trim().split("\n")
      const at = (subject: string) => {
        const hash = subjects.find((line) => line.endsWith(` ${subject}`))?.split(" ")[0]
        const replayed = report.commits.find((entry) => entry.commit === hash)
        return {
          baseline: replayed?.baseline.ok,
          baselineFailed: replayed?.baseline.counts.failed,
          normal: replayed?.normal.counts,
          failures: (replayed?.normal.failures ?? []).map((failure) => failure.step),
          mismatches: replayed?.mismatches
        }
      }
      // The repository's own CI has two steps. Split, the first is three: four in all, and nothing to reuse yet.
      expect(at("base")).toEqual({
        baseline: true,
        baselineFailed: 0,
        normal: { hit: 0, ran: 4, failed: 0, skipped: 0 },
        failures: [],
        mismatches: []
      })
      // `types` never opened the docs: it is answered from its record. `format` and `spell` read them and run again,
      // and so does the whole of the loose step, which holds all three.
      const docs = at("docs only")
      expect({ ...docs, normal: undefined }).toEqual({
        baseline: true,
        baselineFailed: 0,
        normal: undefined,
        failures: [],
        mismatches: []
      })
      expect(docs.normal).toMatchObject({ failed: 0, skipped: 0 })
      expect((docs.normal?.hit ?? 0) + (docs.normal?.ran ?? 0)).toBe(4)
      if (manager.kept) expect(docs.normal).toEqual({ hit: 1, ran: 3, failed: 0, skipped: 0 })
      // `spell` fails, so `types` does not run and the step fails, as `&&` has it in the repository's own CI. The
      // loose step goes on past the failure and passes on its last script, in both.
      expect(at("a misspelt word in the docs")).toEqual({
        baseline: false,
        baselineFailed: 1,
        normal: { hit: 0, ran: 2, failed: 1, skipped: 1 },
        // The failure names the script that failed.
        failures: ["ci.yml:check: Check (spell)"],
        mismatches: []
      })
      expect(report.mismatches).toBe(0)
      expect(outcome.code).toBe(0)
    },
    540_000
  )
})

/**
 * A script split into one step per link runs each link as it ran inside the
 * whole script: the same links, in the same order, each with the same
 * environment, variable for variable.
 *
 * Every case runs the real package manager twice in a real directory: once
 * as the repository's CI runs the step (`npm run check`), and once as the
 * steps of the split run it, each link's command by itself and a link after a
 * failed one not at all. Every script writes down the environment it was
 * started with, and the two runs are compared.
 *
 * Each package manager installed on this machine has a case: npm, pnpm,
 * Yarn 1 and Bun.
 */
import { spawnSync } from "node:child_process"
import { chmodSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { afterAll, describe, expect, it } from "vitest"
import { shell } from "../../src/contract/Inventory.vibe"
import * as Script from "../../src/decompose/Script.vibe"
import { remove, temporary } from "../cli/repo.ts"

const made: Array<string> = []
afterAll(() => made.forEach(remove))

interface Manager {
  readonly name: Script.Manager
  /** The words a script runs another script with. */
  readonly run: string
  /** The command of the CI step. */
  readonly step: string
  /** The script the step runs. */
  readonly script: string
  /** Files that say which release runs the scripts. */
  readonly files: Readonly<Record<string, string>>
}

const managers: ReadonlyArray<Manager> = [
  { name: "npm", run: "npm run", step: "npm run check", script: "check", files: {} },
  { name: "pnpm", run: "pnpm run", step: "pnpm check", script: "check", files: {} },
  // `yarn check` is Yarn's own command, so the script has another name.
  {
    name: "yarn",
    run: "yarn",
    step: "yarn verify",
    script: "verify",
    files: { "yarn.lock": "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n" }
  },
  { name: "bun", run: "bun run", step: "bun run check", script: "check", files: {} }
]

const installed = (name: string): boolean => spawnSync(name, ["--version"], { cwd: "/" }).status === 0

/** Writes the environment a script was started with to `$DUMP/<name>.json`, then fails when told to. */
const dump = [
  "const fs = require('node:fs')",
  "const name = process.argv[2]",
  "fs.writeFileSync(`${process.env.DUMP}/${name}.json`, JSON.stringify(process.env))",
  "fs.appendFileSync(`${process.env.DUMP}/order`, `${name}\\n`)",
  "process.exit(process.env.FAIL === name ? 3 : 0)",
  ""
].join("\n")

/**
 * A package whose `check` runs four scripts in a chain two deep: `types`
 * is itself `types:a && types:b`, and `lint` has a `pre` script.
 */
const scriptsOf = (manager: Manager): Readonly<Record<string, string>> => ({
  [manager.script]: `${manager.run} types && ${manager.run} lint && ${manager.run} format`,
  types: `${manager.run} types:a && ${manager.run} types:b`,
  "types:a": "node dump.js types-a",
  "types:b": "node dump.js types-b",
  prelint: "node dump.js prelint",
  lint: "node dump.js lint",
  format: "node dump.js format"
})

const write = (root: string, files: Readonly<Record<string, string>>): void => {
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true })
    writeFileSync(join(root, path), content)
  }
}

/** A directory holding the package, at `directory` below its top. */
const packageAt = (manager: Manager, directory: string, extra: Readonly<Record<string, string>> = {}): string => {
  const root = temporary(`script-${manager.name}`)
  made.push(root)
  const inside = (file: string): string => directory === "" ? file : `${directory}/${file}`
  write(root, {
    [inside("package.json")]: JSON.stringify({
      name: "fixture",
      version: "1.2.3",
      private: true,
      scripts: scriptsOf(manager)
    }),
    [inside("dump.js")]: dump,
    ...Object.fromEntries(Object.entries(manager.files).map(([file, content]) => [inside(file), content])),
    ...extra
  })
  return root
}

/** The machine's search path without entries read from the directory a command starts in, as a CI machine has it. */
const machinePath = (process.env["PATH"] ?? "").split(":").filter((entry) => entry.startsWith("/")).join(":")

/** Runs one command as a CI step is run, in `cwd`, and gives its exit code. */
const runStep = (command: string, cwd: string, dumps: string, fail: string | undefined): number => {
  mkdirSync(dumps, { recursive: true })
  const [program, ...flags] = shell
  const ran = spawnSync(program, [...flags, command], {
    cwd,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
    env: { ...process.env, PATH: machinePath, DUMP: dumps, ...(fail === undefined ? {} : { FAIL: fail }) }
  })
  return ran.status ?? -1
}

/** The scripts that ran, in order. */
const orderOf = (dumps: string): ReadonlyArray<string> =>
  existsSync(join(dumps, "order")) ? readFileSync(join(dumps, "order"), "utf8").trim().split("\n") : []

/**
 * A search path as the directories a program is found in, in order: each
 * directory once, at its first place, and the directory of shims Yarn makes
 * for one run under one name.
 */
const searched = (path: string): ReadonlyArray<string> => [
  ...new Set(path.split(":").map((entry) => resolve(entry).replace(/\/yarn--\d+-[\d.]+$/, "/yarn--run")))
]

/** The environment a script was started with, with its search path as the directories searched. */
const environmentOf = (dumps: string, name: string): Readonly<Record<string, unknown>> => {
  const { PATH, ...rest } = JSON.parse(readFileSync(join(dumps, `${name}.json`), "utf8")) as Record<string, string>
  return { ...rest, PATH: searched(PATH ?? "") }
}

/** The steps a split makes of the CI step, as their commands. */
const linksOf = (manager: Manager, root: string, directory: string): ReadonlyArray<Script.Link> => {
  const decision = Script.decide(
    { command: manager.step, cwd: directory, env: {} },
    (path) => existsSync(join(root, path)) ? readFileSync(join(root, path), "utf8") : undefined
  )
  return decision.kind === "links" ? decision.links : []
}

/** Runs the links in order and stops at the first that fails, as steps that each wait for the one before do. */
const runLinks = (links: ReadonlyArray<Script.Link>, cwd: string, dumps: string, fail?: string): number => {
  for (const link of links) {
    const code = runStep(link.command, cwd, dumps, fail)
    if (code !== 0) return code
  }
  return 0
}

/**
 * What differs between a script's environment inside the whole and in its
 * own step, as `name: whole | split`.
 *
 * Two things are left out, each for a reason a person can check:
 *
 * - Yarn puts its global directory before npm's `node-gyp` shims in a first
 *   run and after them in a run inside a script. Only `node-gyp` could be
 *   found in both, so for Yarn the directories are compared and their order
 *   is not.
 * - `SHLVL` counts shells. Bun starts every script under bash, which adds
 *   one, and a split has one shell fewer for each script that ran around the
 *   link. npm, pnpm and Yarn start scripts under `sh`, which on this system
 *   leaves the count alone: for them it is compared.
 *
 * `besides` names more variables to leave out.
 */
const differences = (
  whole: string,
  split: string,
  name: string,
  manager: Manager,
  besides: ReadonlyArray<string> = []
): ReadonlyArray<string> => {
  const one = environmentOf(whole, name)
  const other = environmentOf(split, name)
  const settled = (value: unknown): unknown =>
    manager.name === "yarn" && Array.isArray(value) ? [...value].sort() : value
  // Where each run wrote is the test's own variable.
  const own = [...(manager.name === "bun" ? ["DUMP", "SHLVL"] : ["DUMP"]), ...besides]
  return [...new Set([...Object.keys(one), ...Object.keys(other)])].sort()
    .filter((key) => !own.includes(key))
    .filter((key) => JSON.stringify(settled(one[key])) !== JSON.stringify(settled(other[key])))
    .map((key) => `${key}: ${JSON.stringify(one[key])} | ${JSON.stringify(other[key])}`)
}

const everyScript = ["types-a", "types-b", "prelint", "lint", "format"]

describe.each(managers)("a script chain run by $name", (manager) => {
  const available = installed(manager.name)

  it.skipIf(!available)(
    "runs the same scripts in the same order with the same environment as one step per link",
    () => {
      const root = packageAt(manager, "")
      const links = linksOf(manager, root, "")
      expect(links.map((link) => link.name)).toEqual(["types:a", "types:b", "lint", "format"])
      const whole = join(root, "dumps-whole")
      const split = join(root, "dumps-split")
      expect(runStep(manager.step, root, whole, undefined)).toBe(0)
      expect(runLinks(links, root, split)).toBe(0)
      // The link's own `pre` script still runs: the package manager runs the link.
      expect(orderOf(whole)).toEqual(everyScript)
      expect(orderOf(split)).toEqual(everyScript)
      for (const name of everyScript) expect(differences(whole, split, name, manager), name).toEqual([])
      // What the package manager gives a script is there in both: this is what a link run as a bare command would lose.
      const lint = environmentOf(split, "lint")
      expect(lint["npm_lifecycle_event"]).toBe("lint")
      expect(lint["npm_package_name"]).toBe("fixture")
      expect(lint["PATH"] as ReadonlyArray<string>).toContain(join(root, "node_modules/.bin"))
    },
    300_000
  )

  it.skipIf(!available)("stops at the link that fails, as `&&` does, and fails as the whole fails", () => {
    const root = packageAt(manager, "")
    const links = linksOf(manager, root, "")
    const whole = join(root, "dumps-whole")
    const split = join(root, "dumps-split")
    // The second link of four fails: the two after it never run, in the whole and in the split.
    const wholeCode = runStep(manager.step, root, whole, "types-b")
    const splitCode = runLinks(links, root, split, "types-b")
    expect(wholeCode).not.toBe(0)
    expect(splitCode).not.toBe(0)
    expect(orderOf(whole)).toEqual(["types-a", "types-b"])
    expect(orderOf(split)).toEqual(["types-a", "types-b"])
    // A hook that fails stops the chain too.
    const hookWhole = join(root, "hook-whole")
    const hookSplit = join(root, "hook-split")
    expect(runStep(manager.step, root, hookWhole, "prelint")).not.toBe(0)
    expect(runLinks(links, root, hookSplit, "prelint")).not.toBe(0)
    expect(orderOf(hookWhole)).toEqual(["types-a", "types-b", "prelint"])
    expect(orderOf(hookSplit)).toEqual(orderOf(hookWhole))
  }, 300_000)

  it.skipIf(!available)("gives a package below the repository's top the same environment", () => {
    const root = packageAt(manager, "packages/app")
    const links = linksOf(manager, root, "packages/app")
    expect(links).toHaveLength(4)
    const cwd = join(root, "packages/app")
    const whole = join(root, "dumps-whole")
    const split = join(root, "dumps-split")
    expect(runStep(manager.step, cwd, whole, undefined)).toBe(0)
    expect(runLinks(links, cwd, split)).toBe(0)
    expect(orderOf(split)).toEqual(orderOf(whole))
    for (const name of everyScript) expect(differences(whole, split, name, manager), name).toEqual([])
  }, 300_000)
})

describe("a package that installs its own npm", () => {
  it.skipIf(!installed("npm"))("runs that npm for a link, as the script around the link did", () => {
    const manager = managers[0] as Manager
    const root = packageAt(manager, "")
    // What an install leaves when a dependency brings an `npm` of its own: it says what it was asked, then runs the
    // real one.
    const real = spawnSync("bash", ["-c", "command -v npm"], { encoding: "utf8" }).stdout.trim()
    const own = join(root, "node_modules/.bin/npm")
    write(root, { "node_modules/.bin/npm": `#!/bin/sh\necho "$*" >> "$DUMP/npm"\nexec ${real} "$@"\n` })
    chmodSync(own, 0o755)
    const links = linksOf(manager, root, "")
    const whole = join(root, "dumps-whole")
    const split = join(root, "dumps-split")
    expect(runStep(manager.step, root, whole, undefined)).toBe(0)
    expect(runLinks(links, root, split)).toBe(0)
    const ownRuns = (dumps: string): ReadonlyArray<string> =>
      readFileSync(join(dumps, "npm"), "utf8").trim().split("\n")
    // Inside the whole, the step's own `npm run check` is the machine's npm and every run inside it is the
    // package's. As steps, each link is run by the package's npm too. The one run a split has no step for is
    // `types`, which only named two others.
    expect(ownRuns(whole)).toEqual(["run types", "run types:a", "run types:b", "run lint", "run format"])
    expect(ownRuns(split)).toEqual(["run types:a", "run types:b", "run lint", "run format"])
    // `_` is the shell's own: bash sets it to the program it starts, and `sh` here passes it on. Inside the whole it
    // names the machine's npm, which bash started for the step; in a link's step it names the package's npm, which
    // bash started for the link. Every other variable is the same.
    for (const name of everyScript) expect(differences(whole, split, name, manager, ["_"]), name).toEqual([])
    expect(readdirSync(split).sort()).toEqual(readdirSync(whole).sort())
    // Without the package's directory first on the path, a link would be run by the machine's npm.
    const bare = join(root, "dumps-bare")
    for (const link of links) expect(runStep(link.command.replace(/^PATH="[^"]*" /, ""), root, bare, undefined)).toBe(0)
    expect(existsSync(join(bare, "npm"))).toBe(false)
  }, 300_000)
})

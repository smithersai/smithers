test("history rejects a one-sided fingerprint edit, removal or kind change before merge", () => {
  const base = { stores: { a: entry("original") }, payloads: {} }
  checkHistory(undefined, base)
  checkHistory(base, { stores: { a: { kind: "synced", versions: { 1: "original", 2: "new" } } }, payloads: {} })
  assert.throws(() => checkHistory(base, { stores: { a: entry("changed") } }), /versions.1/)
  assert.throws(() => checkHistory(base, { stores: {} }), /stores.a/)
  assert.throws(() => checkHistory(base, { stores: { a: { kind: "local", versions: { 1: "original" } } } }), /stores.a/)
})


test("old lock writers normalize with the SDK's code-unit ordering and no duplicate mutations", () => {
  const value = canonicalHistory({ stores: { z: entry("z"), A: entry("A"), a: entry("a") }, payloads: {}, mutations: ["z", "A", "a", "z"] })
  assert.deepEqual(Object.keys(value.stores), ["A", "a", "z"])
  assert.deepEqual(value.mutations, ["A", "a", "z"])
  // A merge sorts keys; the lock still reads in the SDK's order, so a merged lane's diff is only its versions.
  const merged = canonicalHistory(mergeHistory({ stores: {}, payloads: {}, mutations: [] }, { stores: { a: entry("a") }, payloads: {}, mutations: ["ask"] }, { stores: {}, payloads: { p: entry("p") }, mutations: [] }))
  assert.deepEqual(Object.keys(merged), ["stores", "payloads", "mutations"])
})

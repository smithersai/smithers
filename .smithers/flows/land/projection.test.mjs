import { strict as assert } from "node:assert"
import { test } from "node:test"
import { decodeProjection } from "./projection.mjs"
const receipt = (value) => `SMITHERS_TARGET_INDEX ${Buffer.from(JSON.stringify(value)).toString("base64")}\n`
test("accepts one valid projection among runner progress messages, preserving the actual generated bytes", () => {
  assert.equal(decodeProjection(`progress\n${receipt([{ label: "//:x" }])}done\n`), '[{"label":"//:x"}]')
})
test("refuses missing, duplicate, malformed and duplicate-label receipts", () => {
  for (const value of [[], {}, [{ label: "local" }], [{ label: "//:x" }, { label: "//:x" }]]) assert.throws(() => decodeProjection(receipt(value)), /Invalid/)
  assert.throws(() => decodeProjection("nothing"), /exactly one/)
  assert.throws(() => decodeProjection(receipt([{ label: "//:x" }]).repeat(2)), /exactly one/)
  assert.throws(() => decodeProjection("SMITHERS_TARGET_INDEX eA==\n"), /JSON/)
})

import { strict as assert } from "node:assert"
import { test } from "node:test"
import { decodeProjection, regenerateIndex } from "./projection.mjs"
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, existsSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { jj } from "./numbering.mjs"
const receipt = (value) => `SMITHERS_TARGET_INDEX ${Buffer.from(JSON.stringify(value)).toString("base64")}\n`
test("accepts one valid projection among runner progress messages, preserving the actual generated bytes", () => {
  assert.equal(decodeProjection(`progress\n${receipt([{ label: "//:x" }])}done\n`), '[{"label":"//:x"}]')
})
test("refuses missing, duplicate, malformed and duplicate-label receipts", () => {
  for (const value of [[], {}, [{ label: "local" }], [{ label: "//:x" }, { label: "//:x" }]]) assert.throws(() => decodeProjection(receipt(value)), /Invalid/)
  assert.throws(() => decodeProjection("nothing"), /exactly one/)
  assert.throws(() => decodeProjection(receipt([{ label: "//:x" }]).repeat(2)), /exactly one/)
  assert.throws(() => decodeProjection("SMITHERS_TARGET_INDEX eA==\n"), /JSON/)
})

function fixture(t, miniBody, boxBody) {
  const root = mkdtempSync(join(tmpdir(), "land-projection-"))
  t.after(() => rmSync(root, { recursive: true, force: true }))
  jj(root, ["git", "init", "."])
  mkdirSync(join(root, ".smithers"))
  writeFileSync(join(root, ".smithers/target-index.json"), "[]\n")
  writeFileSync(join(root, ".node-version"), "26.5.0\n")
  writeFileSync(join(root, ".gitignore"), ".env\nnode_modules/\n")
  writeFileSync(join(root, ".env"), "ignored test sentinel\n")
  const runner = (name, body) => {
    const path = join(root, name)
    writeFileSync(path, `#!${process.execPath}\n${body}\n`, { mode: 0o755 })
    return path
  }
  const mini = runner("mini-run", miniBody)
  const box = runner("cfbox", boxBody)
  jj(root, ["status"])
  return { root, mini, box }
}

for (const [name, body] of [
  ["exit 7", "process.exit(7)"],
  ["stderr capacity timeout", 'console.error("CAPACITY_TIMEOUT: all slots reserved"); process.exit(1)'],
  ["stdout capacity timeout", 'console.log("CAPACITY_TIMEOUT: all slots reserved"); process.exit(1)']
]) test(`mini ${name} falls back to cfbox and accepts the same checked receipt`, async (t) => {
  const expected = [{ label: "//:checked" }]
  const { root, mini, box } = fixture(t, body, `
    const assert = require("node:assert/strict"), fs = require("node:fs")
    const args = process.argv.slice(2)
    assert.equal(args[0], "run")
    assert.equal(args[args.indexOf("--cpu") + 1], "2")
    const tree = args[args.indexOf("--") - 1]
    assert.equal(fs.existsSync(tree + "/.jj"), false)
    assert.equal(fs.existsSync(tree + "/.git"), false)
    assert.equal(fs.existsSync(tree + "/.env"), false)
    assert.equal(fs.readFileSync(tree + "/.smithers/target-index.json", "utf8"), "[]\\n")
    fs.writeFileSync(".jj/box-tree", tree)
    assert.deepEqual(args.slice(args.indexOf("--") + 1), ["node", ".smithers/flows/land/index-projection.mjs", "--cloud"])
    console.log(${JSON.stringify(receipt(expected).trim())})
  `)
  await regenerateIndex(root, mini, undefined, box)
  assert.equal(readFileSync(join(root, ".smithers/target-index.json"), "utf8"), JSON.stringify(expected))
  assert.equal(existsSync(readFileSync(join(root, ".jj/box-tree"), "utf8")), false)
})

test("mini admission gets a few seconds, never 0, and a real failure does not invoke cfbox", async (t) => {
  // An older mini-run read 0 as already expired and skipped even an idle mini: every land fell to cfbox.
  const { root, mini, box } = fixture(t, `
    require("node:assert/strict").equal(process.env.MINI_RUN_WAIT_SECONDS, "5")
    console.error("generation failed"); process.exit(23)
  `, 'require("node:fs").writeFileSync("box-called", "yes")')
  await assert.rejects(regenerateIndex(root, mini, undefined, box), /generation failed/)
  assert.equal(existsSync(join(root, "box-called")), false)
  assert.equal(readFileSync(join(root, ".smithers/target-index.json"), "utf8"), "[]\n")
})

test("cfbox failure or invalid receipt never publishes an index", async (t) => {
  for (const body of ['console.error("box failed"); process.exit(19)', 'console.log("no receipt")']) {
    const { root, mini, box } = fixture(t, "process.exit(7)", body)
    await assert.rejects(regenerateIndex(root, mini, undefined, box), /box failed|exactly one/)
    assert.equal(readFileSync(join(root, ".smithers/target-index.json"), "utf8"), "[]\n")
  }
})

test("successful mini receipt does not invoke cfbox", async (t) => {
  const expected = [{ label: "//:mini" }]
  const { root, mini, box } = fixture(t, `console.log(${JSON.stringify(receipt(expected).trim())})`, 'process.exit(99)')
  await regenerateIndex(root, mini, undefined, box)
  assert.equal(readFileSync(join(root, ".smithers/target-index.json"), "utf8"), JSON.stringify(expected))
})

test("source edits during cfbox execution refuse the projection and clean its staging tree", async (t) => {
  const { root, mini, box } = fixture(t, 'process.exit(7)', `
    const fs = require("node:fs"), args = process.argv.slice(2)
    fs.writeFileSync(".jj/box-tree", args[args.indexOf("--") - 1])
    fs.writeFileSync("source-edit", "changed")
    console.log(${JSON.stringify(receipt([{ label: "//:stale" }]).trim())})
  `)
  await assert.rejects(regenerateIndex(root, mini, undefined, box), /Source changed/)
  assert.equal(readFileSync(join(root, ".smithers/target-index.json"), "utf8"), "[]\n")
  assert.equal(existsSync(readFileSync(join(root, ".jj/box-tree"), "utf8")), false)
})

/** Pin Pierre's SSR renderer without Shiki's entire language/theme catalogs. */
import { build } from "esbuild"
import { readFileSync, writeFileSync } from "node:fs"
import { dirname } from "node:path"
import { fileURLToPath } from "node:url"
import { gzipSync } from "node:zlib"

// These languages cover repository source/config. Other languages retain
// Pierre's line numbers, word diffs and annotations with plain text tokens.
const languages = [
  "typescript", "tsx", "javascript", "jsx", "json", "jsonc", "css", "html",
  "markdown", "yaml", "toml", "shellscript", "zsh", "sql", "go", "rust",
  "python", "c", "cpp", "csharp", "java", "dockerfile", "diff", "xml", "vue", "svelte"
]
const pierreDirectory = dirname(fileURLToPath(import.meta.resolve("@pierre/diffs")))
const entry = `
import { getSingularPatch, getFiletypeFromFileName } from "@pierre/diffs";
import { preloadFileDiff } from "@pierre/diffs/ssr";
const supported = new Set(${JSON.stringify(languages)});
export async function preloadPatchDiff({patch, options, annotations}) {
  const fileDiff = getSingularPatch(patch);
  const lang = fileDiff.lang ?? getFiletypeFromFileName(fileDiff.name);
  fileDiff.lang = supported.has(lang) ? lang : "text";
  return preloadFileDiff({fileDiff, options, annotations});
}`
const result = await build({
  stdin: { contents: entry, resolveDir: fileURLToPath(new URL(".", import.meta.url)) },
  bundle: true, write: false, minify: true, format: "iife", globalName: "pierreReview",
  platform: "neutral", target: "es2022", legalComments: "inline", metafile: true,
  plugins: [{
    name: "review-highlighter",
    setup(build) {
      build.onResolve({ filter: /^shiki$/ }, () => ({ path: "shiki", namespace: "review-highlighter" }))
      build.onLoad({ filter: /.*/, namespace: "review-highlighter" }, () => ({
        resolveDir: pierreDirectory,
        contents: `
          export * from "shiki/core";
          import { createHighlighterCore, createSingletonShorthands } from "shiki/core";
          export const createHighlighter = createHighlighterCore;
          export const { codeToHtml } = /* @__PURE__ */ createSingletonShorthands(createHighlighterCore);
          export { createJavaScriptRegexEngine } from "shiki/engine/javascript";
          export { createOnigurumaEngine } from "shiki/engine/oniguruma";
          export const bundledLanguages = {${languages.map(lang => `${JSON.stringify(lang)}: () => import(${JSON.stringify(`@shikijs/langs/${lang}`)})`).join(",")}};
        `
      }))
      // The public SSR API exposes no custom highlighter. Its theme resolver
      // otherwise retains every Shiki theme although this wrapper exposes only
      // Pierre's built-in light/dark themes. Keep the real collection API.
      build.onLoad({ filter: /[/\\]collections[/\\]shiki\.js$/ }, ({ path }) => ({
        resolveDir: dirname(path),
        contents: 'import { createThemeCollection } from "../modules/createThemeCollection.js"; export const shikiThemes = createThemeCollection({ themes: [] });'
      }))
    }
  }]
})
if (Object.values(result.metafile.outputs).some(output => output.imports.length > 0)) {
  throw new Error("The offline Pierre renderer must have no external imports")
}
const encoded = gzipSync(result.outputFiles[0].contents, { level: 9 }).toString("base64")
const output = `/** Generated by generate-pierre-runtime.mjs from pinned dependencies; part of the measured flow closure. */\nconst runtime = ${JSON.stringify(encoded)}\nexport function pierreRuntimeGzipBase64(): string { return runtime }\n`
const path = new URL("./pierreRuntimeGzipBase64.ts", import.meta.url)
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== output) throw new Error("Pierre renderer resource is stale; regenerate it")
} else writeFileSync(path, output)
console.log(`Pierre SSR: ${result.outputFiles[0].contents.length} JS bytes; ${encoded.length} gzip/base64 bytes; ${languages.length} languages`)

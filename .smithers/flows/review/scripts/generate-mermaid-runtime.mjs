/** Generate one offline Mermaid runtime inside the measured flow closure. */
import { build } from "esbuild"
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { gzipSync } from "node:zlib"

// Bundle the ESM entry once, including its lazy diagrams. The distribution's
// prebuilt min.js expects a top-level var to become a global property, which
// fails when evaluated by our strict inline loader. This bridge lives in the
// same scope as the generated IIFE and publishes only the public Mermaid API.
const result = await build({
  stdin: { contents: 'export { default } from "mermaid"', resolveDir: fileURLToPath(new URL(".", import.meta.url)) },
  bundle: true, write: false, minify: true, format: "iife", globalName: "mermaidRuntime",
  platform: "browser", target: "es2022", legalComments: "inline", metafile: true,
  footer: { js: "globalThis.mermaid = mermaidRuntime.default;" }
})
if (Object.values(result.metafile.outputs).some(output => output.imports.length > 0)) {
  throw new Error("The offline Mermaid runtime must have no external imports")
}
const encoded = gzipSync(result.outputFiles[0].contents, { level: 9 }).toString("base64")
const output = `/** Generated by scripts/generate-mermaid-runtime.mjs; runtime resource is part of the pinned flow closure. */\nconst runtime = ${JSON.stringify(encoded)};\nexport function mermaidRuntimeGzipBase64(): string { return runtime; }\n`
const path = new URL("../src/walkthrough/mermaidRuntimeGzipBase64.ts", import.meta.url)
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== output) throw new Error("Mermaid renderer resource is stale; regenerate it")
} else writeFileSync(path, output)
console.log(`Mermaid: ${result.outputFiles[0].contents.length} JS bytes; ${encoded.length} gzip/base64 bytes`)
